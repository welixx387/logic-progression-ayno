const LEVEL_LISTS: [Level, Classic[]][] = [
  [1, L1],
  [2, L2],
  [3, L3],
  [4, L4],
  [5, L5],
]

export function classic(): Task[] {
  const tasks: Task[] = []
  for (const [level, list] of LEVEL_LISTS) {
    const rng = createRng(`classic:${level}`)
    list.forEach((c, i) => {
      tasks.push({
        id: `classic-${level}-${String(i + 1).padStart(2, '0')}`,
        module: 'classic',
        level,
        kind: c.kind,
        prompt: c.prompt,
        ...(c.options ? { options: rng.shuffle(c.options) } : {}),
        answer: c.answer,
        ...(c.accept ? { accept: c.accept } : {}),
        hint: c.hint,
        solution: c.solution,
      })
    })
  }
  return tasks
}

/** Словари для заданий на память: предметы, имена, профессии, цвета, места. */

export type Gender = 'm' | 'f' | 'n'

export interface Noun {
  w: string
  g: Gender
  /** Смысловая группа: похожие слова — самые коварные неверные варианты. */
  c: string
}

const group = (c: string, items: string): Noun[] =>
  items.split(',').map((x) => {
    const [w, g] = x.trim().split(':')
    return { w, g: g as Gender, c }
  })


const NOTHING = 'Ничего определённого сказать нельзя'

function conditionals(level: Level, rng: Rng, index: number): Draft | null {
  const r = rng.pick(RULES)
  const rule = `«Если ${r.a}, то ${r.b}»`
  const key = RULES.indexOf(r)
  if (level <= 3) {
    const kinds = level === 1 ? [0] : level === 2 ? [0, 1] : [0, 1, 2, 3]
    const k = kinds[index % kinds.length]
    const fact = [r.a, r.nb, r.b, r.na][k]
    const right = [cap(r.b), cap(r.na), NOTHING, NOTHING][k]
    const wrong = [cap(r.nb), cap(r.na), cap(r.a), cap(r.b), NOTHING].filter((x) => x !== right)
    const why = [
      `Условие выполнено (${r.a}), значит, выполнено и следствие: ${r.b}. Это правило «модус поненс».`,
      `Если бы выполнялось условие «${r.a}», то было бы верно и «${r.b}». Но ${r.nb} — значит, ${r.na}. Это правило «модус толленс»: из ложности следствия следует ложность условия.`,
      `Правило говорит только, что будет, если ${r.a}. Но ${r.b} могло случиться и по другой причине. Вывод «значит, ${r.a}» — частая ошибка («утверждение следствия»).`,
      `Правило ничего не говорит о том, что бывает, когда ${r.na}. Вывод «значит, ${r.nb}» — ошибка («отрицание условия»).`,
    ][k]
    return choice(
      `Известно правило: ${rule}.\nИзвестно: ${fact}. Что из этого следует?`,
      right,
      rng.shuffle(wrong),
      rng,
      'Правило «если A, то B» работает только в одну сторону: из A следует B, из «не B» — «не A».',
      [why],
      `c:${level}:${key}:${k}`,
      { ref: k < 2 ? 0 : 1 },
      level === 1 ? 3 : 4,
    )
  }
  if (level === 4) {
    const t = index % 2
    if (t === 0)
      return choice(
        `Какое утверждение равносильно правилу ${rule}?`,
        `Если ${r.nb}, то ${r.na}.`,
        [`Если ${r.b}, то ${r.a}.`, `Если ${r.na}, то ${r.nb}.`, `${cap(r.a)}, и ${r.b}.`],
        rng,
        'Равносильно только контрапозиции: «если не B, то не A».',
        [`«Если A, то B» равносильно «если не B, то не A» (контрапозиция). Обратное («если B, то A») и противоположное («если не A, то не B») — другие утверждения, они могут быть ложными, когда исходное верно.`],
        `e:${key}`,
        { ref: 2 },
      )
    return choice(
      `Правило: ${rule}. Какое утверждение ему НЕ противоречит, но и не следует из него?`,
      `Если ${r.b}, то ${r.a}.`,
      [`Если ${r.nb}, то ${r.na}.`, `${cap(r.a)}, но ${r.nb}.`],
      rng,
      'Одно утверждение следует из правила, одно ему противоречит, а одно — независимо от него.',
      [`«Если ${r.nb}, то ${r.na}» — следует из правила (это контрапозиция).`, `«${cap(r.a)}, но ${r.nb}» — противоречит правилу.`, `«Если ${r.b}, то ${r.a}» — обратное утверждение: правило его не доказывает и не опровергает.`],
      `o:${key}`,
      { ref: 2 },
      3,
    )
  }
  const t = index % 2
  if (t === 0)
    return choice(
      `Правило: ${rule}. Какое утверждение верно?`,
      `«${cap(r.a)}» — достаточное условие для «${r.b}».`,
      [`«${cap(r.a)}» — необходимое условие для «${r.b}».`, `«${cap(r.b)}» — достаточное условие для «${r.a}».`, `Эти условия равносильны.`],
      rng,
      'Если A гарантирует B, то A — достаточное условие для B, а B — необходимое для A.',
      [`«Если A, то B» означает: A достаточно для B (A гарантирует B), а B необходимо для A (без B не бывает A).`, `Здесь A — «${r.a}», B — «${r.b}».`],
      `s:${key}`,
      { ref: 3 },
    )
  return choice(
    `Утверждение «${cap(r.a)}, только если ${r.b}» означает…`,
    `Если ${r.a}, то ${r.b}.`,
    [`Если ${r.b}, то ${r.a}.`, `Если ${r.na}, то ${r.nb}.`, `${cap(r.a)} тогда и только тогда, когда ${r.b}.`],
    rng,
    '«A, только если B» — значит, без B не бывает A.',
    [`«A только если B» значит: A не бывает без B. То есть если A — то обязательно B.`, `Это не то же самое, что «если B, то A»: B может быть и без A.`],
    `y:${key}`,
    { ref: 3 },
  )
}


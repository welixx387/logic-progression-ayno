function euler(level: Level, rng: Rng, index: number): Draft | null {
  if (level <= 3) {
    const p = rng.pick(PAIRS2)
    const both = rng.int(1, 8)
    const onlyX = rng.int(2, 12)
    const onlyY = rng.int(2, 12)
    const none = rng.int(level === 1 ? 1 : 0, 9)
    const total = both + onlyX + onlyY + none
    const X = onlyX + both
    const Y = onlyY + both
    const t = level === 1 ? 0 : index % 3
    const people = (n: number) => `${n} ${plural(n, 'человек', 'человека', 'человек')}`
    const head = `В группе ${people(total)}. ${cap(p.v)} ${p.x} ${X}, ${p.y} — ${Y}, ${p.both} — ${both}.`
    if (t === 0)
      return numeric(`${head} Сколько человек ${p.none}?`, none, 'Сложите тех, кто выбрал хотя бы что-то: но тех, кто выбрал оба, считают дважды.', [`Хотя бы в одну из групп входят ${X} + ${Y} − ${both} = ${X + Y - both} ${plural(X + Y - both, 'человек', 'человека', 'человек')}: тех, кто в обеих, вычитаем, иначе они посчитаны дважды.`, `Ни в одну группу не входят: ${total} − ${X + Y - both} = ${none}.`], `n:${total}:${X}:${Y}:${both}`, { ref: 0 })
    if (t === 1)
      return numeric(`${head} Сколько человек ${p.v} только ${p.x}?`, onlyX, 'Из всей группы уберите тех, кто входит и во вторую.', [`${cap(p.v)} ${p.x} — ${X}, из них ${both} — ${p.both}.`, `Только ${p.x}: ${X} − ${both} = ${onlyX}.`], `o:${total}:${X}:${Y}:${both}`, { ref: 0 })
    return numeric(`В группе ${people(total)}. ${cap(p.v)} ${p.x} ${X}, ${p.y} — ${Y}, а ${none} ${p.none}. Сколько человек ${p.v} ${p.both}?`, both, 'Выбравших хотя бы что-то: всего минус никого. Сравните с суммой двух групп.', [`Хотя бы в одну группу входят ${total} − ${none} = ${total - none}.`, `Сумма групп ${X} + ${Y} = ${X + Y} больше этого числа ровно на тех, кто посчитан дважды: ${X + Y} − ${total - none} = ${both}.`], `b:${total}:${X}:${Y}:${none}`, { ref: 0 })
  }
  const [x, y, z] = rng.pick(TRIPLES)
  const r = {
    xyz: rng.int(1, 4),
    xy: rng.int(1, 5),
    xz: rng.int(1, 5),
    yz: rng.int(1, 5),
    x: rng.int(2, 9),
    y: rng.int(2, 9),
    z: rng.int(2, 9),
    none: rng.int(0, 6),
  }
  const X = r.x + r.xy + r.xz + r.xyz
  const Y = r.y + r.xy + r.yz + r.xyz
  const Z = r.z + r.xz + r.yz + r.xyz
  const XY = r.xy + r.xyz
  const XZ = r.xz + r.xyz
  const YZ = r.yz + r.xyz
  const union = X + Y + Z - XY - XZ - YZ + r.xyz
  const total = union + r.none
  const head = `В классе ${total} ${plural(total, 'ученик', 'ученика', 'учеников')}, каждый может записаться в несколько кружков. ${cap(x)} выбрали ${X}, ${y} — ${Y}, ${z} — ${Z}; ${x} и ${y} — ${XY}, ${x} и ${z} — ${XZ}, ${y} и ${z} — ${YZ}, все три кружка — ${r.xyz}.`
  if (level === 4 || index % 2 === 0)
    return numeric(`${head} Сколько учеников не записались никуда?`, r.none, 'Формула включений-исключений: сложить группы, вычесть попарные пересечения, прибавить тройное.', [`Хотя бы в один кружок записались: ${X} + ${Y} + ${Z} − ${XY} − ${XZ} − ${YZ} + ${r.xyz} = ${union}.`, `Попарные пересечения вычитаем (их посчитали дважды), а тройное прибавляем обратно (его сначала посчитали трижды, а потом трижды вычли).`, `Никуда не записались: ${total} − ${union} = ${r.none}.`], `t:${total}:${X}:${Y}:${Z}:${XY}:${XZ}:${YZ}:${r.xyz}`, { ref: 1 })
  return numeric(`${head} Сколько учеников выбрали только ${x}?`, r.x, 'Из группы вычтите попарные пересечения с ней и прибавьте тройное (его вычли дважды).', [`Только ${x}: ${X} − ${XY} − ${XZ} + ${r.xyz} = ${r.x}.`, `Тройное пересечение прибавляем, потому что оно входило и в «${x} и ${y}», и в «${x} и ${z}» — его вычли два раза.`], `u:${total}:${X}:${Y}:${Z}:${XY}:${XZ}:${YZ}:${r.xyz}`, { ref: 1 })
}

// ——— Принцип Дирихле ———

const SOCKS: [string, string][] = [
  ['красных', 'красного'],
  ['синих', 'синего'],
  ['белых', 'белого'],
  ['чёрных', 'чёрного'],
  ['зелёных', 'зелёного'],
]

function pigeonhole(level: Level, rng: Rng, index: number): Draft | null {
  const t = level === 1 ? 0 : level === 2 ? index % 2 : level === 3 ? index % 3 : index % 4
  if (t === 3 || (level >= 4 && index % 4 === 0)) {
    const variants: [string, number, string][] = [
      ['в одном месяце', 12, 'месяцев'],
      ['в один день недели', 7, 'дней недели'],
      ['под одним знаком зодиака', 12, 'знаков зодиака'],
    ]
    const [what, boxes, boxName] = rng.pick(variants)
    const m = rng.int(2, level >= 4 ? 5 : 3)
    const n = boxes * (m - 1) + 1
    return numeric(`Какое наименьшее число людей нужно собрать, чтобы наверняка хотя бы ${m} из них родились ${what}?`, n, 'Представьте самый неудачный случай: в каждую «коробку» попало на одного меньше, чем нужно.', [`«Коробок» — ${boxes} (${boxName}).`, `Худший случай: в каждой по ${m - 1} — это ${boxes} · ${m - 1} = ${boxes * (m - 1)} человек, и ни в одной нет ${m}.`, `Следующий, ${n}-й человек, обязательно окажется в коробке, где уже ${m - 1}. Ответ: ${n}.`], `b:${what}:${m}`, { ref: 0 })
  }
  const k = level <= 2 ? 2 : level <= 4 ? 3 : 4
  const colors = rng.sample(SOCKS, k)
  const counts = colors.map(() => rng.int(3, 12))
  const listed = colors.map((c, j) => `${counts[j]} ${c[0]}`).join(', ')
  const intro = `В тёмном ящике лежат носки: ${listed}. Носки достают не глядя.`
  if (t === 0) {
    const n = k + 1
    return numeric(`${intro} Какое наименьшее число носков нужно достать, чтобы среди них наверняка были два одного цвета?`, n, 'Худший случай: сначала попадается по одному носку каждого цвета.', [`Цветов ${k}. В худшем случае первые ${k} ${plural(k, 'носок', 'носка', 'носков')} — все разных цветов.`, `Следующий, ${n}-й, обязательно совпадёт по цвету с одним из них. Ответ: ${n}.`], `p:${counts.join(',')}`, { ref: 0 })
  }
  if (t === 1) {
    const i = rng.int(0, k - 1)
    const others = counts.reduce((s, c, j) => (j === i ? s : s + c), 0)
    const n = others + 2
    return numeric(`${intro} Какое наименьшее число носков нужно достать, чтобы среди них наверняка были два ${colors[i][1]} цвета?`, n, 'В худшем случае сначала достаются все носки других цветов.', [`Носков других цветов: ${others}. В худшем случае достаём их все.`, `Потом нужны ещё 2 носка ${colors[i][1]} цвета: ${others} + 2 = ${n}.`], `c:${counts.join(',')}:${i}`, { ref: 1 })
  }
  const m = 3
  const worst = counts.reduce((s, c) => s + Math.min(c, m - 1), 0)
  const n = worst + 1
  if (counts.every((c) => c < m)) return null
  return numeric(`${intro} Какое наименьшее число носков нужно достать, чтобы среди них наверняка было ${m} носка одного цвета?`, n, 'Худший случай: каждого цвета достали на один меньше, чем нужно (если столько есть).', [`В худшем случае каждого цвета достаём по ${m - 1} (или все, если их меньше): ${counts.map((c) => Math.min(c, m - 1)).join(' + ')} = ${worst}.`, `Следующий носок даст третий носок одного из цветов. Ответ: ${n}.`], `t:${counts.join(',')}`, { ref: 1 })
}

// ——— Чётность ———

function parity(level: Level, rng: Rng, index: number): Draft | null {
  const t = level === 1 ? index % 2 : level === 2 ? index % 3 : level === 3 ? 1 + (index % 3) : 2 + (index % 3)
  if (t === 0) {
    const n = rng.int(3, 25)
    const kind = rng.chance(0.25) ? 'чётных' : 'нечётных'
    const even = kind === 'чётных' || n % 2 === 0
    return choice(`Сложили ${n} ${kind} чисел. Какой может быть сумма?`, even ? 'Только чётной' : 'Только нечётной', [even ? 'Только нечётной' : 'Только чётной', 'Может быть любой'], rng, 'Каждое нечётное число — это чётное плюс 1.', [kind === 'чётных' ? 'Сумма чётных чисел всегда чётна.' : `Каждое нечётное число даёт «лишнюю» единицу. ${n} единиц в сумме дают ${n % 2 === 0 ? 'чётное' : 'нечётное'} число, поэтому сумма ${even ? 'чётна' : 'нечётна'}.`], `s:${n}:${kind}`, { ref: 0 }, 3)
  }
  if (t === 1) {
    const n = rng.int(4, 15)
    const k = rng.int(1, n - 1)
    const can = (n * k) % 2 === 0
    return choice(`В компании ${n} человек. Может ли быть так, что каждый пожал руку ровно ${k} ${plural(k, 'другому', 'другим', 'другим')}?`, can ? 'Да' : 'Нет', [can ? 'Нет' : 'Да'], rng, 'Посчитайте, сколько «концов рукопожатий» получится у всех вместе.', [`В каждом рукопожатии участвуют двое, поэтому сумма рукопожатий всех людей — чётное число (удвоенное число рукопожатий).`, `Здесь сумма равна ${n} · ${k} = ${n * k} — ${can ? 'это чётное число, и такое возможно (например, если рассадить людей по кругу и связать с соседями по нужному правилу)' : 'нечётное число, а значит, так быть не может'}.`], `h:${n}:${k}`, { ref: 1 }, 2)
  }
  if (t === 2) {
    const n = rng.int(level <= 3 ? 4 : 10, level <= 3 ? 12 : 40)
    const sum = (n * (n + 1)) / 2
    return choice(`На доске написаны числа от 1 до ${n}. Разрешается стереть любые два числа и записать вместо них их сумму или разность. Так делают, пока не останется одно число. Каким оно будет?`, sum % 2 === 0 ? 'Чётным' : 'Нечётным', [sum % 2 === 0 ? 'Нечётным' : 'Чётным', 'Зависит от ходов'], rng, 'Найдите то, что не меняется при каждом ходе, — инвариант.', ['Сумма и разность двух чисел имеют одинаковую чётность, поэтому чётность суммы всех чисел на доске не меняется — это инвариант.', `В начале сумма 1 + 2 + … + ${n} = ${sum} — ${sum % 2 === 0 ? 'чётная' : 'нечётная'}. Значит, последнее число будет ${sum % 2 === 0 ? 'чётным' : 'нечётным'}.`], `b:${n}`, { ref: 2 }, 3)
  }
  if (t === 3) {
    const n = rng.int(3, 21)
    const can = n % 2 === 0
    return choice(`Шахматный конь сделал ${n} ${plural(n, 'ход', 'хода', 'ходов')}. Мог ли он вернуться на ту клетку, с которой начал?`, can ? 'Да' : 'Нет', [can ? 'Нет' : 'Да'], rng, 'Каким цветом клетки, на которую конь приходит каждым ходом?', ['Каждым ходом конь меняет цвет клетки: с белой — на чёрную, с чёрной — на белую.', `Чтобы вернуться на исходную клетку (того же цвета), нужно чётное число ходов. ${n} — ${can ? 'чётное, и вернуться можно (например, туда-обратно)' : 'нечётное, поэтому конь окажется на клетке другого цвета'}.`], `k:${n}`, { ref: 1 }, 2)
  }
  const n = rng.int(4, 12)
  const s = rng.int(n, 5 * n)
  // Монеты 1, 3 и 5 — все нечётные: сумма нечётных монет имеет чётность их количества.
  const can = s % 2 === n % 2
  return choice(`Можно ли набрать ровно ${s} рублей с помощью ${n} ${plural(n, 'монеты', 'монет', 'монет')} достоинством 1, 3 и 5 рублей?`, can ? 'Да' : 'Нет', [can ? 'Нет' : 'Да'], rng, 'Все монеты нечётные. Какой будет чётность суммы?', ['Все монеты нечётные, поэтому сумма n нечётных монет имеет ту же чётность, что и n.', `Здесь монет ${n} (${n % 2 === 0 ? 'чётное' : 'нечётное'} число), а нужно ${s} (${s % 2 === 0 ? 'чётное' : 'нечётное'}). ${can ? 'Чётности совпадают, и сумма лежит между ' + n + ' (все по 1) и ' + 5 * n + ' (все по 5) — набрать можно, заменяя рублёвые монеты на трёх- и пятирублёвые (каждая замена добавляет 2 или 4).' : 'Чётности разные — набрать нельзя.'}`], `m:${n}:${s}`, { ref: 0 }, 2)
}

// ——— Взвешивания ———

const pow3 = (k: number) => 3 ** k
const ceilLog3 = (n: number) => {
  let k = 0
  while (pow3(k) < n) k++
  return k
}

function balancedTernary(x: number): number[] {
  const digits: number[] = []
  while (x !== 0) {
    let r = x % 3
    x = Math.floor(x / 3)
    if (r === 2) {
      r = -1
      x += 1
    }
    digits.push(r)
  }
  return digits
}

function weighing(level: Level, rng: Rng, index: number): Draft | null {
  const t = level <= 2 ? index % 2 : level === 3 ? index % 3 : 2 + (index % 2)
  if (t === 0) {
    const n = rng.int(level === 1 ? 3 : 10, level === 1 ? 9 : level === 2 ? 27 : 100)
    const k = ceilLog3(n)
    return numeric(`Среди ${n} одинаковых на вид монет одна фальшивая — она легче остальных. За какое наименьшее число взвешиваний на чашечных весах без гирь её можно наверняка найти?`, k, 'Каждое взвешивание делит монеты на три кучки: левую, правую и отложенную.', [`Одно взвешивание различает 3 исхода: легче левая чаша, легче правая или равновесие (фальшивая — среди отложенных).`, `За k взвешиваний можно выбрать фальшивую из 3ᵏ монет: ${Array.from({ length: k + 1 }, (_, i) => `3${sup(i)} = ${pow3(i)}`).join(', ')}.`, `${pow3(k - 1)} < ${n} ≤ ${pow3(k)}, значит, нужно ${k} ${plural(k, 'взвешивание', 'взвешивания', 'взвешиваний')}.`], `c:${n}`, { ref: 0 })
  }
  if (t === 1) {
    const k = rng.int(2, level <= 2 ? 3 : 5)
    return numeric(`Среди нескольких монет одна фальшивая, легче остальных. Какое наибольшее число монет можно проверить за ${k} ${plural(k, 'взвешивание', 'взвешивания', 'взвешиваний')} на чашечных весах, чтобы наверняка найти фальшивую?`, pow3(k), 'Каждое взвешивание утраивает число монет, из которых можно выбрать одну.', [`Каждое взвешивание делит кучу на три части, поэтому за одно взвешивание — 3 монеты, за два — 9 и т. д.`, `За ${k}: 3${sup(k)} = ${pow3(k)}.`], `m:${k}`, { ref: 0 })
  }
  if (t === 2) {
    const x = rng.int(3, level <= 3 ? 15 : 31)
    const used = x.toString(2).split('').filter((b) => b === '1').length
    const parts = x
      .toString(2)
      .split('')
      .reverse()
      .map((b, i) => (b === '1' ? 2 ** i : 0))
      .filter(Boolean)
      .reverse()
    return numeric(`Есть по одной гире 1, 2, 4, 8 и 16 г. Гири можно класть только на одну чашу. Сколько гирь понадобится, чтобы уравновесить груз в ${x} г?`, used, 'Разложите число на степени двойки.', [`${x} = ${parts.join(' + ')} — это двоичная запись числа ${x} (${x.toString(2)}₂).`, `Нужно ${used} ${plural(used, 'гиря', 'гири', 'гирь')}.`], `b:${x}`, { ref: 1 })
  }
  const x = rng.int(5, level <= 4 ? 40 : 120)
  const d = balancedTernary(x)
  const left = d.map((v, i) => (v === 1 ? pow3(i) : 0)).filter(Boolean)
  const right = d.map((v, i) => (v === -1 ? pow3(i) : 0)).filter(Boolean)
  const used = left.length + right.length
  return numeric(`Есть по одной гире 1, 3, 9, 27 и 81 г. Гири можно класть на обе чаши весов. Какое наименьшее число гирь понадобится, чтобы уравновесить груз в ${x} г?`, used, 'Гиря на чаше с грузом вычитается, на другой чаше — прибавляется.', [`Гири на пустой чаше: ${left.join(' + ')} г${right.length ? `; вместе с грузом лежат: ${right.join(' + ')} г` : ''}.`, `${left.join(' + ')}${right.length ? ` − ${right.join(' − ')}` : ''} = ${x}.`, `Это троичная запись числа с цифрами −1, 0 и 1: каждая гиря либо на одной чаше, либо на другой, либо не нужна. Понадобится ${used} ${plural(used, 'гиря', 'гири', 'гирь')}.`], `t:${x}`, { ref: 2 })
}


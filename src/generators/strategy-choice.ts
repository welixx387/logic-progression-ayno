function dtree(level: Level, rng: Rng, index: number): Draft | null {
  const si = rng.int(0, STORIES.length - 1)
  const st = STORIES[si]
  const unit = 'тыс. ₽'
  const head = `${st.intro} Результаты — прибыль в тыс. ₽ (минус — убыток).`
  const ev = (pairs: [number, number][]) => pairs.reduce((s, [p, x]) => s + (p * x) / 100, 0)
  const evText = (pairs: [number, number][]) => pairs.map(([p, x]) => `${dec(p / 100, 1)} · ${par(x)}`).join(' + ')

  if (level === 1) {
    const p = rng.pick(P)
    const A = rng.int(5, 30) * 10
    const B = rng.int(-10, 5) * 10
    const e = ev([
      [p, A],
      [100 - p, B],
    ])
    const lines = [`${st.risky}:`, `• ${st.good} (вероятность ${p}%) → ${pm(A)}`, `• ${st.bad} (${100 - p}%) → ${pm(B)}`]
    return numeric(`${head}\nКакова ожидаемая (средняя) прибыль варианта «${st.risky}»?`, e, 'Умножьте каждый исход на его вероятность и сложите.', [`${evText([[p, A], [100 - p, B]])} = ${sg(e)} ${unit}.`, 'Это средний результат, если бы такое решение принималось много раз.'], `1:${si}:${p}:${A}:${B}`, { display: { type: 'lines', lines }, ref: 0 })
  }
  if (level === 2 || level === 3) {
    const p1 = rng.pick([20, 30, 40, 50, 60])
    const p2 = level === 3 ? rng.pick([20, 30, 40].filter((x) => x + p1 < 100)) : 0
    const p3 = 100 - p1 - p2
    const A = rng.int(8, 40) * 10
    const M = rng.int(0, 8) * 10
    const B = rng.int(-15, -2) * 10
    const pairs: [number, number][] = level === 3 ? [[p1, A], [p2, M], [p3, B]] : [[p1, A], [p3, B]]
    const e = ev(pairs)
    const S = rng.int(2, 25) * 10
    if (S === e) return null
    const lines = [`${st.risky}:`, `• ${st.good} (${p1}%) → ${pm(A)}`, ...(level === 3 ? [`• ${st.mid} (${p2}%) → ${pm(M)}`] : []), `• ${st.bad} (${p3}%) → ${pm(B)}`, `${st.safe} → ${pm(S)} (наверняка)`]
    const better = e > S ? st.risky : st.safe
    const steps = [`Ожидаемая прибыль варианта «${st.risky}»: ${evText(pairs)} = ${sg(e)} ${unit}.`, `Вариант «${st.safe}» даёт ${sg(S)} ${unit} наверняка.`, `${sg(Math.max(e, S))} > ${sg(Math.min(e, S))}, поэтому по ожидаемой прибыли лучше «${better}».`]
    if (index % 2 === 0)
      return choice(`${head}\nКакое решение выгоднее по ожидаемой прибыли?`, better, [st.risky, st.safe].filter((x) => x !== better), rng, 'Посчитайте среднюю прибыль рискованного варианта и сравните с надёжным.', steps, `2:${level}:${si}:${pairs.flat().join(',')}:${S}`, { display: { type: 'lines', lines }, ref: 0 }, 2)
    return numeric(`${head}\nНа сколько тыс. ₽ ожидаемая прибыль лучшего решения больше, чем у другого?`, Math.abs(e - S), 'Сначала найдите ожидаемую прибыль рискованного варианта.', [...steps, `Разница: ${Math.abs(e - S)} ${unit}.`], `d:${level}:${si}:${pairs.flat().join(',')}:${S}`, { display: { type: 'lines', lines }, ref: 0 })
  }
  if (level === 4 || index % 2 === 0) {
    // Двухшаговое дерево: после неудачи — второе решение. Решаем с конца.
    const p = rng.pick([30, 40, 50, 60, 70])
    const q = rng.pick([20, 30, 40, 50, 60])
    const A = rng.int(4, 20) * 100
    const Bq = rng.int(-8, 0) * 10
    const C = rng.int(5, 30) * 10
    const D = rng.int(2, 10) * 100
    const E = rng.int(-3, 0) * 100
    const retry = (q * D + (100 - q) * E) / 100 - C
    if (retry === Bq) return null
    const second = Math.max(retry, Bq)
    const total = (p * A + (100 - p) * second) / 100
    const lines = [
      `${st.risky}:`,
      `• ${st.good} (${p}%) → ${pm(A)}`,
      `• ${st.bad} (${100 - p}%) → нужно решить:`,
      `   — ${st.quit} → ${pm(Bq)}`,
      `   — ${st.retry} за ${C}: удача (${q}%) → ${pm(D)}, неудача (${100 - q}%) → ${pm(E)}`,
    ]
    return numeric(
      `${head}\nКакова ожидаемая прибыль варианта «${st.risky}», если и второе решение принимать правильно?`,
      total,
      'Решайте с конца: сначала выберите лучшее действие после неудачи, потом считайте среднее для первого шага.',
      [`После неудачи: «${st.retry}» даёт ${dec(q / 100, 1)} · ${par(D)} + ${dec(1 - q / 100, 1)} · ${par(E)} − ${C} = ${sg(retry)}, «${st.quit}» — ${sg(Bq)}.`, `Лучше «${retry > Bq ? st.retry : st.quit}»: ${sg(second)}.`, `Весь вариант: ${dec(p / 100, 1)} · ${par(A)} + ${dec(1 - p / 100, 1)} · ${par(second)} = ${sg(total)} ${unit}.`],
      `4:${si}:${p}:${q}:${A}:${Bq}:${C}:${D}:${E}`,
      { display: { type: 'lines', lines }, ref: 1 },
    )
  }
  // Порог вероятности: при каком шансе успеха рискованный вариант не хуже надёжного.
  const pStar = rng.pick([15, 20, 25, 30, 35, 40, 45, 55, 60, 65, 70, 75])
  const B = rng.int(-10, 0) * 20
  const span = rng.int(5, 25) * 20
  const A = B + span
  const S = B + (pStar * span) / 100
  if (!Number.isInteger(S) || S <= 0) return null
  const lines = [`${st.risky}:`, `• ${st.good} → ${pm(A)}`, `• ${st.bad} → ${pm(B)}`, `${st.safe} → ${pm(S)} (наверняка)`]
  return numeric(
    `${head}\nПри какой наименьшей вероятности того, что ${st.good}, рискованный вариант станет не хуже надёжного по ожидаемой прибыли? Ответ — в процентах.`,
    pStar,
    'Обозначьте вероятность за p и приравняйте ожидаемую прибыль рискованного варианта к надёжной.',
    [`p · ${par(A)} + (1 − p) · ${par(B)} = ${sg(S)}.`, `p · ${span} = ${sg(S)} − ${B < 0 ? `(${sg(B)})` : sg(B)} = ${S - B}, p = ${S - B} : ${span} = ${dec(pStar / 100, 2)} = ${pStar}%.`, 'Если шанс успеха выше — выгоднее рисковать, если ниже — выбрать надёжное.'],
    `5:${si}:${A}:${B}:${S}`,
    { display: { type: 'lines', lines }, ref: 2 },
  )
}


const CRIT_REF: Record<Crit, number> = { wald: 0, maximax: 0, laplace: 1, bayes: 1, savage: 2, hurwicz: 3 }

function scoreRows(v: number[][], crit: Crit, a: number, probs: number[]): { score: number[]; better: 'max' | 'min'; line: (i: number) => string } {
  const colMax = v[0].map((_, j) => Math.max(...v.map((r) => r[j])))
  switch (crit) {
    case 'wald':
      return { score: v.map((r) => Math.min(...r)), better: 'max', line: (i) => `худший исход ${sg(Math.min(...v[i]))}` }
    case 'maximax':
      return { score: v.map((r) => Math.max(...r)), better: 'max', line: (i) => `лучший исход ${sg(Math.max(...v[i]))}` }
    case 'laplace':
      return { score: v.map((r) => r.reduce((s, x) => s + x, 0)), better: 'max', line: (i) => `сумма ${v[i].map(sg).join(' + ').replace(/\+ −/g, '− ')} = ${sg(v[i].reduce((s, x) => s + x, 0))}` }
    case 'savage': {
      const reg = v.map((r) => r.map((x, j) => colMax[j] - x))
      return { score: reg.map((r) => Math.max(...r)), better: 'min', line: (i) => `сожаления ${reg[i].join(', ')} → наибольшее ${Math.max(...reg[i])}` }
    }
    case 'hurwicz': {
      const h = v.map((r) => (a * Math.max(...r) + (10 - a) * Math.min(...r)) / 10)
      return { score: h, better: 'max', line: (i) => `${dec(a / 10, 1)} · ${par(Math.max(...v[i]))} + ${dec(1 - a / 10, 1)} · ${par(Math.min(...v[i]))} = ${sg(h[i])}` }
    }
    case 'bayes': {
      const e = v.map((r) => r.reduce((s, x, j) => s + (x * probs[j]) / 100, 0))
      return { score: e, better: 'max', line: (i) => `${v[i].map((x, j) => `${dec(probs[j] / 100, 1)} · ${par(x)}`).join(' + ')} = ${sg(e[i])}` }
    }
  }
}

function winner(score: number[], better: 'max' | 'min'): number | null {
  const best = better === 'max' ? Math.max(...score) : Math.min(...score)
  return score.filter((s) => s === best).length === 1 ? score.indexOf(best) : null
}

function uncertainty(level: Level, rng: Rng, index: number): Draft | null {
  const fi = rng.int(0, FRAMES.length - 1)
  const f = FRAMES[fi]
  const n = level <= 2 ? 3 : 4
  const rows = f.rows.slice(0, n)
  const v = rows.map(() => f.cols.map(() => rng.int(-5, 30) * 10))
  const plan: Crit[][] = [[], ['wald', 'maximax'], ['wald', 'maximax', 'laplace'], ['savage', 'laplace', 'savage'], ['savage', 'hurwicz', 'bayes'], ['savage', 'hurwicz', 'bayes']]
  const crit = plan[level][index % plan[level].length]
  const a = rng.pick([3, 4, 6, 7])
  const pr = rng.pick([
    [20, 50, 30],
    [30, 50, 20],
    [10, 60, 30],
    [40, 40, 20],
    [20, 30, 50],
    [50, 30, 20],
  ])
  const s = scoreRows(v, crit, a, pr)
  const w = winner(s.score, s.better)
  if (w === null) return null
  // Со второго уровня ответ должен отличаться от выбора хотя бы одного другого критерия — иначе критерии не различить.
  if (level >= 2) {
    const others = (['wald', 'maximax', 'laplace', 'savage'] as Crit[]).filter((c) => c !== crit).map((c) => winner(scoreRows(v, c, a, pr).score, scoreRows(v, c, a, pr).better))
    if (others.every((o) => o === w)) return null
    if (level >= 4 && others.filter((o) => o !== w).length < 2) return null
  }
  const display = { type: 'table' as const, head: ['Вариант', ...f.cols], rows: rows.map((r, i) => [r, ...v[i].map(sg)]) }
  const steps = [...rows.map((r, i) => `${r}: ${s.line(i)}.`), `${s.better === 'max' ? 'Наибольшее' : 'Наименьшее'} значение — у варианта «${rows[w]}».`]
  if (crit === 'savage') steps.unshift('Сожаление = лучший результат в этом столбце − результат варианта.')
  const key = `${fi}:${v.flat().join(',')}`
  if (level === 3 && index % 2 === 1 && crit !== 'savage') {
    // Числовой вопрос: наибольшее сожаление конкретного варианта.
    const sv = scoreRows(v, 'savage', a, pr)
    const i = rng.int(0, n - 1)
    return numeric(`${f.intro}\nНасколько в худшем случае можно пожалеть о выборе варианта «${rows[i]}»? Введите наибольшее сожаление (сожаление = лучший результат при этом исходе − результат варианта).`, sv.score[i], CRIT_HINT.savage, ['Сожаление = лучший результат в этом столбце − результат варианта.', `${rows[i]}: ${sv.line(i)}.`], `r:${key}:${i}`, { display, ref: 2 })
  }
  const notes = Object.fromEntries(rows.map((r, i) => [r, `${s.line(i)[0].toUpperCase()}${s.line(i).slice(1)}.`]))
  return choice(`${f.intro}\n${CRIT_ASK[crit](a, pr, f.cols)}`, rows[w], rows.filter((_, i) => i !== w), rng, CRIT_HINT[crit], steps, `${crit}:${key}${crit === 'hurwicz' ? `:${a}` : ''}${crit === 'bayes' ? `:${pr.join(',')}` : ''}`, { display, notes, ref: CRIT_REF[crit] }, n)
}


const rub = (n: number) => `${n.toLocaleString('ru-RU')} ₽`

function money(rng: Rng): Draft {
  const t = rng.int(0, 2)
  if (t === 0) {
    const gross = rng.int(3, 20) * 10000
    const tax = (gross * 13) / 100
    const net = gross - tax
    return {
      kind: 'number',
      prompt: `Зарплата работника до вычета налога — ${rub(gross)} в месяц. Налог на доходы физических лиц — 13%. Сколько рублей он получит на руки?`,
      answer: String(net),
      hint: 'Найдите 13% от зарплаты и вычтите их.',
      solution: `Налог: ${rub(gross)} · 0,13 = ${rub(tax)}. На руки: ${rub(gross)} − ${rub(tax)} = ${rub(net)}.`,
      key: `ndfl:${gross}`,
    }
  }
  if (t === 1) {
    const sum = rng.int(1, 10) * 50000
    const rate = rng.pick([5, 6, 8, 10, 12, 15])
    const res = sum + (sum * rate) / 100
    return {
      kind: 'number',
      prompt: `Вкладчик положил в банк ${rub(sum)} под ${rate}% годовых. Сколько рублей будет на счёте через год?`,
      answer: String(res),
      hint: 'Через год к вкладу прибавятся проценты от его суммы.',
      solution: `Проценты: ${rub(sum)} · ${rate}% = ${rub((sum * rate) / 100)}. Итого: ${rub(res)}.`,
      key: `deposit:${sum}:${rate}`,
    }
  }
  const price = rng.int(2, 20) * 100
  const q = rng.int(5, 40) * 10
  const cost = price * q - rng.int(1, 10) * 5000
  if (cost <= 0) return money(rng)
  const profit = price * q - cost
  return {
    kind: 'number',
    prompt: `Фирма продала ${q} товаров по ${rub(price)}. Её издержки — ${rub(cost)}. Какова прибыль фирмы в рублях?`,
    answer: String(profit),
    hint: 'Прибыль = выручка − издержки; выручка = цена · количество.',
    solution: `Выручка: ${rub(price)} · ${q} = ${rub(price * q)}. Прибыль: ${rub(price * q)} − ${rub(cost)} = ${rub(profit)}.`,
    key: `profit:${price}:${q}:${cost}`,
  }
}

function macro(rng: Rng): Draft {
  if (rng.chance(0.5)) {
    const nominal = rng.int(6, 20)
    const inflation = rng.int(2, nominal - 1)
    return {
      kind: 'number',
      prompt: `Банк выплачивает по вкладу ${nominal}% годовых, а инфляция за год составила ${inflation}%. Какова примерно реальная процентная ставка (в %)?`,
      answer: String(nominal - inflation),
      hint: 'Реальная ставка ≈ номинальная ставка − инфляция.',
      solution: `${nominal}% − ${inflation}% ≈ ${nominal - inflation}%: на столько на самом деле выросла покупательная способность вклада.`,
      key: `real:${nominal}:${inflation}`,
    }
  }
  const force = rng.pick([40, 50, 60, 75, 80])
  const rate = rng.pick([4, 5, 6, 8, 10, 12])
  const unemployed = (force * rate) / 100
  const employed = force - unemployed
  const f = (x: number) => String(x).replace('.', ',')
  return {
    kind: 'number',
    prompt: `В стране ${f(employed)} млн занятых и ${f(unemployed)} млн безработных. Каков уровень безработицы (в %)?`,
    answer: String(rate),
    hint: 'Уровень безработицы = безработные : рабочая сила · 100%. Рабочая сила = занятые + безработные.',
    solution: `Рабочая сила: ${f(employed)} + ${f(unemployed)} = ${force} млн. ${f(unemployed)} : ${force} · 100% = ${rate}%.`,
    key: `unemp:${force}:${rate}`,
  }
}

function fact(level: Level, rng: Rng): Draft {
  const i = rng.int(0, FACTS[level].length - 1)
  return factDraft(FACTS[level][i], rng, `fact:${level}:${i}`, HINT)
}

function generate(level: Level, rng: Rng, index: number): Draft | null {
  if (level === 2 && index % 2 === 1) return money(rng)
  if (level === 4 && index % 3 === 2) return macro(rng)
  return fact(level, rng)
}


const T = { 1: 6, 2: 6, 3: 6, 4: 6, 5: 6 } as const
const HINT = 'Вспомните, что проходили на уроках по этой теме.'

export type Calc = (rng: Rng, index: number) => Draft | null

/** Чередует вопросы по фактам и расчётные задачи (каждое второе задание — расчёт, если он есть для класса). */
export function subject(module: ModuleGenerator['module'], facts: Record<Level, Fact[]>, calc: Partial<Record<Level, Calc>>, every = 2): ModuleGenerator {
  return {
    module,
    targets: T,
    make: (level, rng, index) => {
      const c = calc[level]
      if (c && (facts[level].length === 0 || index % every !== 0)) return c(rng, index)
      const i = rng.int(0, facts[level].length - 1)
      return factDraft(facts[level][i], rng, `f:${level}:${i}`, HINT)
    },
  }
}

/** Несократимая дробь «a/b». */
const frac = (a: number, b: number) => {
  if (a === 0) return '0'
  const g = gcd(a, b)
  return b / g === 1 ? String(a / g) : `${a / g}/${b / g}`
}

/** Отвлекающие дроби рядом с a/b. */
function fracWrong(a: number, b: number, extra: [number, number][] = []): string[] {
  const right = frac(a, b)
  const cand = [...extra, [a + 1, b], [Math.max(1, a - 1), b], [b - a, b], [a, b + 6], [a * 2, b], [1, b]]
    .filter(([x, y]) => x > 0 && x < y)
    .map(([x, y]) => frac(x, y))
  return [...new Set(cand)].filter((x) => x !== right)
}


// ——— Воронки ———

function funnel(level: Level, rng: Rng, index: number): Draft | null {
  const visitors = rng.pick([1000, 2000, 5000, 10000, 20000])
  const c1 = rng.pick([20, 25, 30, 40, 50])
  const c2 = rng.pick([10, 20, 25, 40, 50])
  const cart = (visitors * c1) / 100
  const buy = (cart * c2) / 100
  if (!Number.isInteger(buy)) return null
  const check = rng.pick([500, 800, 1000, 1500, 2000])
  const display = { type: 'table' as const, head: ['Этап', 'Человек'], rows: [['Зашли на сайт', big(visitors)], ['Положили товар в корзину', big(cart)], ['Оплатили заказ', big(buy)]] }
  const t = level === 1 ? 0 : level === 2 ? index % 2 : level === 3 ? index % 3 : 1 + (index % 3)
  if (t === 0) return numeric('Какова общая конверсия сайта — доля посетителей, которые оплатили заказ (в %)?', (buy / visitors) * 100, 'Разделите число покупателей на число посетителей.', [`${big(buy)} : ${big(visitors)} · 100% = ${dec((buy / visitors) * 100, 2)}%.`], `c:${visitors}:${c1}:${c2}`, { display, ref: 0 })
  if (t === 1) return numeric('Какой процент тех, кто положил товар в корзину, оплатил заказ?', c2, 'Конверсия этапа считается от предыдущего этапа, а не от всех посетителей.', [`${big(buy)} : ${big(cart)} · 100% = ${c2}%.`], `s:${visitors}:${c1}:${c2}`, { display, ref: 0 })
  if (t === 2) return numeric(`Средний чек — ${check} ₽. Какова выручка?`, buy * check, 'Выручка = число покупок × средний чек.', [`${big(buy)} · ${check} = ${big(buy * check)} ₽.`], `r:${visitors}:${c1}:${c2}:${check}`, { display, ref: 1 })
  const ad = rng.pick([100000, 200000, 300000, 500000])
  const margin = rng.pick([20, 30, 40, 50])
  const profit = (buy * check * margin) / 100
  const roi = ((profit - ad) / ad) * 100
  return numeric(`Эти посетители пришли из рекламы, которая стоила ${big(ad)} ₽. Средний чек — ${check} ₽, наценка приносит ${margin}% прибыли с выручки. Каков ROI рекламы (в %, может быть отрицательным; округлите до целых)?`, Math.round(roi), 'ROI = (прибыль − затраты) : затраты · 100%.', [`Выручка: ${big(buy)} · ${check} = ${big(buy * check)} ₽; прибыль ${margin}%: ${big(profit)} ₽.`, `ROI = (${big(profit)} − ${big(ad)}) : ${big(ad)} · 100% ≈ ${dec(Math.round(roi), 0)}%.`, roi < 0 ? 'Реклама не окупилась.' : 'Реклама окупилась.'], `o:${visitors}:${c1}:${c2}:${check}:${ad}:${margin}`, { display, ref: 1 })
}

// ——— A/B-тесты ———

function abtest(level: Level, rng: Rng, index: number): Draft | null {
  const n = rng.pick([1000, 2000, 5000, 10000])
  const ca = rng.pick([2, 3, 4, 5, 6, 8, 10])
  const cb = ca + rng.pick([-1, 1, 2, 3])
  if (cb <= 0) return null
  const a = (n * ca) / 100
  const b = (n * cb) / 100
  const display = { type: 'table' as const, head: ['Вариант', 'Посетителей', 'Покупок'], rows: [['A', big(n), String(a)], ['B', big(n), String(b)]] }
  const t = level === 1 ? 0 : level === 2 ? index % 2 : level === 3 ? 1 + (index % 2) : 2 + (index % 2)
  if (t === 0) return choice('Какой вариант страницы продаёт лучше?', cb > ca ? 'B' : 'A', [cb > ca ? 'A' : 'B', 'Одинаково'], rng, 'Сравните конверсии: покупки : посетители.', [`A: ${a} : ${big(n)} = ${ca}%, B: ${b} : ${big(n)} = ${cb}%.`], `w:${n}:${ca}:${cb}`, { display, ref: 0 }, 3)
  if (t === 1) {
    const uplift = ((cb - ca) / ca) * 100
    return numeric('На сколько процентов конверсия варианта B выше (или ниже), чем у A? Ответ округлите до целых, для снижения — со знаком минус.', Math.round(uplift), 'Относительный прирост = (B − A) : A · 100%.', [`Конверсии: A ${ca}%, B ${cb}% — разница ${dec(cb - ca)} п. п.`, `Относительно A: ${dec(cb - ca)} : ${ca} · 100% ≈ ${dec(Math.round(uplift), 0)}%.`], `u:${n}:${ca}:${cb}`, { display, ref: 0 })
  }
  if (t === 2) {
    const month = rng.pick([30000, 50000, 100000])
    const extra = (month * (cb - ca)) / 100
    return numeric(`Если в месяц на сайт заходит ${big(month)} человек, сколько покупок в месяц добавит переход с A на B (для потерь — со знаком минус)?`, extra, 'Умножьте месячный трафик на разницу конверсий.', [`Разница конверсий: ${dec(cb - ca)} п. п.`, `${big(month)} · ${dec(cb - ca)}% = ${big(extra)} ${plural(Math.abs(extra), 'покупка', 'покупки', 'покупок')}.`], `m:${n}:${ca}:${cb}:${month}`, { display, ref: 0 })
  }
  const small = rng.pick([40, 50, 80, 100])
  const sa = Math.round((small * ca) / 100) + 1
  const sb = sa + rng.int(1, 3)
  return choice(
    `Другой тест: по ${small} посетителей в каждой группе, покупок — ${sa} в A и ${sb} в B. Можно ли уверенно сказать, что B лучше?`,
    'Нет: выборка слишком мала, разница может быть случайной',
    ['Да: у B больше покупок', 'Да, если разница больше одной покупки', 'Нет: A всегда лучше'],
    rng,
    'Погрешность конверсии при n посетителях — около √(p(1 − p)/n). Сравните её с разницей.',
    [`Конверсии: A ${dec((sa / small) * 100, 1)}%, B ${dec((sb / small) * 100, 1)}%.`, `Погрешность при ${small} посетителях — порядка ${dec(Math.sqrt((sa / small) * (1 - sa / small) / small) * 200, 1)} п. п. — больше разницы.`, 'Чтобы заметить разницу в 1–2 п. п., нужны тысячи посетителей в каждой группе.'],
    `s:${small}:${sa}:${sb}`,
    { ref: 1 },
  )
}

// ——— Кредиты и вклады ———

function loans(level: Level, rng: Rng, index: number): Draft | null {
  const t = level === 1 ? 0 : level === 2 ? index % 2 : level === 3 ? 1 + (index % 2) : level === 4 ? 2 + (index % 2) : 3 + (index % 2)
  if (t === 0) {
    const s = rng.pick([10000, 20000, 50000, 100000])
    const r = rng.pick([5, 6, 8, 10, 12])
    const y = rng.int(2, 5)
    const res = s + (s * r * y) / 100
    return numeric(`Вклад ${big(s)} ₽ под ${r}% годовых, проценты не капитализируются (каждый год начисляются только на исходную сумму). Сколько будет на счёте через ${y} ${plural(y, 'год', 'года', 'лет')}?`, res, 'Простые проценты: каждый год добавляется одна и та же сумма.', [`За год: ${big(s)} · ${r}% = ${big((s * r) / 100)} ₽.`, `За ${y}: ${big((s * r * y) / 100)} ₽. Итого ${big(res)} ₽.`], `s:${s}:${r}:${y}`, { ref: 0 })
  }
  if (t === 1) {
    const s = rng.pick([10000, 20000, 50000, 100000])
    const r = rng.pick([5, 10, 20])
    const y = 2
    const res = s * (1 + r / 100) ** y
    return numeric(`Вклад ${big(s)} ₽ под ${r}% годовых с капитализацией (проценты прибавляются к вкладу раз в год). Сколько будет через ${y} года?`, Math.round(res), 'Каждый год сумма умножается на (1 + ставка).', [`Первый год: ${big(s)} · ${dec(1 + r / 100)} = ${big(s * (1 + r / 100))} ₽.`, `Второй год: ${big(s * (1 + r / 100))} · ${dec(1 + r / 100)} = ${big(Math.round(res))} ₽.`, 'Проценты начисляются и на прошлые проценты — это сложный процент.'], `c:${s}:${r}`, { ref: 0 })
  }
  if (t === 2) {
    const s = rng.pick([100000, 200000, 300000, 500000])
    const months = rng.pick([12, 24, 36])
    const pay = Math.round((s * (1 + rng.pick([10, 15, 20, 25]) / 100)) / months / 100) * 100
    const over = pay * months - s
    return numeric(`Кредит ${big(s)} ₽ на ${months} месяцев. Ежемесячный платёж — ${big(pay)} ₽. Какова переплата?`, over, 'Переплата = все платежи − сумма кредита.', [`Всего заплатят: ${big(pay)} · ${months} = ${big(pay * months)} ₽.`, `Переплата: ${big(pay * months)} − ${big(s)} = ${big(over)} ₽.`], `o:${s}:${months}:${pay}`, { ref: 1 })
  }
  if (t === 3) {
    const r = rng.pick([6, 8, 9, 12, 18, 24])
    const years = Math.round(72 / r)
    return numeric(`По «правилу 72», за сколько лет примерно удвоится вклад под ${r}% годовых с капитализацией?`, years, 'Делите 72 на процентную ставку.', [`72 : ${r} = ${years} ${plural(years, 'год', 'года', 'лет')}.`, `Проверка: ${dec(1 + r / 100)}${sup(years)} ≈ ${dec((1 + r / 100) ** years, 2)} — почти вдвое.`], `r:${r}`, { ref: 2 })
  }
  const nominal = rng.int(8, 16)
  const infl = rng.int(4, nominal + 3)
  const real = ((1 + nominal / 100) / (1 + infl / 100) - 1) * 100
  return numeric(`Вклад приносит ${nominal}% годовых, инфляция — ${infl}%. Какова реальная доходность (в %, округлите до десятых; может быть отрицательной)?`, Math.round(real * 10) / 10, 'Реальный рост = (1 + ставка) : (1 + инфляция) − 1.', [`(1 + ${dec(nominal / 100)}) : (1 + ${dec(infl / 100)}) − 1 ≈ ${dec(real / 100, 4)} ≈ ${dec(real, 1)}%.`, `Приближённо: ${nominal} − ${infl} = ${dec(nominal - infl)}% — формула «ставка минус инфляция» работает при небольших числах.`], `i:${nominal}:${infl}`, { ref: 2 })
}

// ——— Выгодная покупка ———

function deals(level: Level, rng: Rng, index: number): Draft | null {
  const t = level === 1 ? 0 : level === 2 ? index % 2 : level === 3 ? 1 + (index % 2) : 2 + (index % 2)
  if (t === 0) {
    const w1 = rng.pick([200, 250, 400, 500])
    const w2 = rng.pick([750, 900, 1000, 1500].filter((w) => w !== w1))
    const p1 = rng.int(4, 20) * 10
    const p2 = Math.round(((p1 / w1) * w2 * (rng.pick([85, 90, 95, 105, 110, 115]) / 100)) / 10) * 10
    const u1 = (p1 / w1) * 100
    const u2 = (p2 / w2) * 100
    if (Math.abs(u1 - u2) < 0.5) return null
    const best = u1 < u2 ? `Пачка ${w1} г` : `Пачка ${w2} г`
    return choice(`Кофе: пачка ${w1} г стоит ${p1} ₽, пачка ${w2} г — ${p2} ₽. Какая покупка выгоднее?`, best, [u1 < u2 ? `Пачка ${w2} г` : `Пачка ${w1} г`, 'Одинаково'], rng, 'Сравните цену за 100 г.', [`За 100 г: ${dec(u1)} ₽ против ${dec(u2)} ₽.`, `Выгоднее: ${best.toLowerCase()}. Большая упаковка не всегда дешевле за килограмм.`], `u:${w1}:${p1}:${w2}:${p2}`, { ref: 0 }, 3)
  }
  if (t === 1) {
    const k = rng.pick([3, 4, 5])
    const pct = Math.round((1 / k) * 1000) / 10
    return numeric(`Акция «${k} товара по цене ${k - 1}». Какова настоящая скидка на каждый товар (в %)? Ответ округлите до десятых.`, pct, 'Вы платите за k − 1 товаров, а получаете k.', [`Бесплатно — 1 из ${k} товаров, то есть ${dec(pct, 1)}% стоимости.`, `Это меньше, чем кажется: «${k} по цене ${k - 1}» — скидка ${dec(pct, 1)}%, а не 50%.`], `k:${k}`, { ref: 1 })
  }
  if (t === 2) {
    const d1 = rng.pick([10, 20, 30])
    const d2 = rng.pick([10, 20, 25, 50])
    const total = 100 - ((100 - d1) * (100 - d2)) / 100
    return numeric(`На товар сначала сделали скидку ${d1}%, а потом ещё ${d2}% от новой цены. Какова общая скидка (в %)?`, total, 'Вторая скидка считается от уже сниженной цены.', [`Цена 100 → ${100 - d1} → ${100 - d1} · ${dec(1 - d2 / 100)} = ${dec(100 - total)}.`, `Общая скидка ${dec(total)}%, а не ${d1 + d2}%.`], `d:${d1}:${d2}`, { ref: 1 })
  }
  const price = rng.pick([2000, 3000, 5000])
  const disc = rng.pick([10, 15, 20])
  const cash = rng.pick([15, 20, 25, 30])
  const a = (price * (100 - disc)) / 100
  return choice(`Товар за ${price} ₽. Вариант 1: скидка ${disc}% сразу. Вариант 2: кешбэк ${cash}% баллами, которые можно потратить только в этом магазине. Что выгоднее, если в этом магазине вы больше покупать не собираетесь?`, 'Скидка', ['Кешбэк', 'Одинаково'], rng, 'Баллы имеют ценность, только если вы их потратите.', [`Со скидкой вы платите ${a} ₽. С кешбэком — все ${price} ₽ и получаете ${(price * cash) / 100} баллов.`, 'Если баллы тратить не на что, их ценность — ноль, поэтому скидка выгоднее, даже когда процент кешбэка больше.', 'Кешбэк стоит сравнивать со скидкой, только если вы точно потратите баллы.'], `c:${price}:${disc}:${cash}`, { ref: 2 }, 3)
}

// ——— Многокритериальная оценка ———

const OPTIONS = [
  ['Ноутбук А', 'Ноутбук Б', 'Ноутбук В'],
  ['Квартира на Лесной', 'Квартира на Садовой', 'Квартира на Речной'],
  ['Секция плавания', 'Секция шахмат', 'Секция робототехники'],
]
const CRITERIA = [
  ['Цена', 'Скорость', 'Вес', 'Экран'],
  ['Цена', 'Метро', 'Площадь', 'Ремонт'],
  ['Интерес', 'Дорога', 'Цена', 'Тренер'],
]

function scoring(level: Level, rng: Rng, index: number): Draft | null {
  const set = rng.int(0, OPTIONS.length - 1)
  const k = level <= 2 ? 3 : 4
  const crit = CRITERIA[set].slice(0, k)
  const weights = crit.map(() => rng.int(1, 5))
  const scores = OPTIONS[set].map(() => crit.map(() => rng.int(1, 10)))
  const totals = scores.map((row) => row.reduce((s, x, i) => s + x * weights[i], 0))
  const best = totals.indexOf(Math.max(...totals))
  if (totals.filter((x) => x === totals[best]).length > 1) return null
  const plainBest = scores.map((r) => r.reduce((s, x) => s + x, 0))
  const display = { type: 'table' as const, head: ['Вариант', ...crit.map((c, i) => `${c} (вес ${weights[i]})`)], rows: OPTIONS[set].map((o, i) => [o, ...scores[i].map(String)]) }
  const t = level === 1 ? 0 : level === 2 ? index % 2 : 1 + (index % 2)
  if (t === 0) {
    const i = rng.int(0, 2)
    return numeric(`Оценки вариантов по критериям (от 1 до 10) и веса критериев — в таблице. Найдите взвешенную сумму баллов варианта «${OPTIONS[set][i]}».`, totals[i], 'Каждую оценку умножьте на вес критерия и сложите.', [`${scores[i].map((x, j) => `${x} · ${weights[j]}`).join(' + ')} = ${totals[i]}.`], `t:${set}:${weights.join(',')}:${scores.flat().join(',')}:${i}`, { display, ref: 0 })
  }
  if (t === 1)
    return choice('Какой вариант лучше по взвешенной сумме баллов?', OPTIONS[set][best], OPTIONS[set].filter((_, i) => i !== best), rng, 'Посчитайте взвешенную сумму для каждого варианта.', [OPTIONS[set].map((o, i) => `${o}: ${scores[i].map((x, j) => `${x}·${weights[j]}`).join(' + ')} = ${totals[i]}`).join('\n'), `Лучший — «${OPTIONS[set][best]}».`, plainBest.indexOf(Math.max(...plainBest)) !== best ? 'Без учёта весов победил бы другой вариант — веса важны.' : ''].filter(Boolean), `b:${set}:${weights.join(',')}:${scores.flat().join(',')}`, { display, ref: 0 }, 3)
  // Какой вес критерия нужно поменять, чтобы победил второй вариант — считаем «запас» победителя.
  const second = totals.map((x, i) => (i === best ? -Infinity : x)).indexOf(Math.max(...totals.filter((_, i) => i !== best)))
  const gap = totals[best] - totals[second]
  return numeric(`На сколько баллов (по взвешенной сумме) лучший вариант опережает второй по счёту?`, gap, 'Найдите взвешенные суммы всех вариантов и сравните два наибольших.', [OPTIONS[set].map((o, i) => `${o}: ${totals[i]}`).join(', '), `Разрыв: ${totals[best]} − ${totals[second]} = ${gap}.`, 'Если разрыв маленький, решение неустойчиво: небольшое изменение весов может поменять победителя.'], `g:${set}:${weights.join(',')}:${scores.flat().join(',')}`, { display, ref: 1 })
}


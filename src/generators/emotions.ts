const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1)

function strongest(rng: Rng): Draft {
  const s = rng.pick(SCALES)
  const words = s.words
  const top = words[words.length - 1]
  const weakest = rng.chance(0.4)
  const answer = weakest ? words[0] : top
  return {
    kind: 'choice',
    prompt: `Эти слова описывают одну и ту же эмоцию разной силы. Какое из них обозначает ${weakest ? 'самую слабую' : 'самую сильную'} степень?`,
    ...withOptions(answer, words.filter((w) => w !== answer), rng, words.length),
    hint: 'Представьте, в какой ситуации вы бы употребили каждое слово.',
    solution: `По возрастанию силы: ${words.join(' → ')}. ${weakest ? `Самая слабая степень — «${answer}»` : `Самая сильная — «${answer}»`}. Точные слова помогают понять, насколько сильно чувство, и выбрать подходящую реакцию.`,
    key: `scale:${s.family}:${weakest}`,
  }
}

function family(rng: Rng): Draft {
  const s = rng.pick(SCALES)
  const w = rng.pick(s.words.filter((x) => x !== s.family))
  const others = SCALES.map((x) => x.family).filter((f) => f !== s.family)
  return {
    kind: 'choice',
    prompt: `К какой эмоции ближе всего слово «${w}» — это та же эмоция, только другой силы?`,
    ...withOptions(s.family, rng.shuffle(others), rng),
    hint: 'Подумайте, что хочется сделать, когда испытываешь это чувство.',
    solution: `«${cap(w)}» — это ${s.words.indexOf(w) < s.words.indexOf(s.family) ? 'слабая' : 'сильная'} степень эмоции «${s.family}»: ${s.words.join(' → ')}.`,
    key: `family:${w}`,
  }
}

function order(rng: Rng): Draft | null {
  const s = rng.pick(SCALES.filter((x) => x.words.length >= 3))
  const w = s.words.slice(0, 3)
  const right = w.join(' → ')
  const perms = [
    [w[1], w[0], w[2]],
    [w[0], w[2], w[1]],
    [w[2], w[1], w[0]],
    [w[1], w[2], w[0]],
    [w[2], w[0], w[1]],
  ].map((p) => p.join(' → '))
  return {
    kind: 'choice',
    prompt: 'Как расположить эти слова по возрастанию силы эмоции?',
    ...withOptions(right, rng.shuffle(perms), rng),
    hint: 'Найдите самое мягкое слово и самое сильное — среднее встанет само.',
    solution: `Правильный порядок: ${right}. Это одна эмоция — «${s.family}» — от слабой степени к сильной.`,
    key: `order:${s.family}`,
  }
}

function opposite(rng: Rng): Draft {
  const e = rng.pick(BASIC)
  const o = OPPOSITE[e]
  return {
    kind: 'choice',
    prompt: `Психолог Роберт Плутчик выделил восемь базовых эмоций и расположил их по кругу так, что напротив каждой стоит противоположная. Какая эмоция противоположна эмоции «${e}»?`,
    ...withOptions(o.to, rng.shuffle(BASIC.filter((x) => x !== e && x !== o.to)), rng),
    hint: 'Противоположные эмоции толкают к противоположным действиям.',
    solution: `В «колесе эмоций» Плутчика напротив эмоции «${e}» стоит «${o.to}»: ${o.why}. Восемь базовых эмоций: радость и печаль, доверие и отвращение, страх и гнев, удивление и ожидание.`,
    key: `opp:${e}`,
  }
}

function dyad(rng: Rng, reverse: boolean): Draft {
  const d = rng.pick(DYADS)
  const others = DYADS.filter((x) => x !== d)
  const pair = (p: [string, string]) => `${p[0]} + ${p[1]}`
  if (reverse) {
    return {
      kind: 'choice',
      prompt: `По модели Плутчика сложные чувства складываются из двух соседних базовых эмоций. Из каких эмоций складывается «${d.name}»?`,
      ...withOptions(pair(d.parts), rng.shuffle(others.map((x) => pair(x.parts))), rng),
      hint: 'Подумайте, какие два простых чувства вы испытываете, когда чувствуете это.',
      solution: `«${cap(d.name)}» = ${pair(d.parts)}. Все первичные сочетания Плутчика: ${DYADS.map((x) => `${x.name} = ${pair(x.parts)}`).join('; ')}.`,
      key: `dyad-r:${d.name}`,
    }
  }
  return {
    kind: 'choice',
    prompt: `По модели Плутчика сложные чувства складываются из двух соседних базовых эмоций. Какое чувство получается из сочетания «${d.parts[0]}» и «${d.parts[1]}»?`,
    ...withOptions(d.name, rng.shuffle(others.map((x) => x.name)), rng),
    hint: 'Представьте, что вы испытываете обе эмоции сразу. Как бы вы назвали это состояние?',
    solution: `${cap(d.parts[0])} + ${d.parts[1]} = ${d.name}. Например: ${
      {
        любовь: 'радость от человека и доверие к нему',
        покорность: 'доверие к сильному и страх перед ним',
        трепет: 'страх и удивление перед чем-то огромным — грозой, океаном',
        неодобрение: 'неприятное удивление и грусть от чужого поступка',
        раскаяние: 'печаль и отвращение к собственному поступку',
        презрение: 'отвращение и гнев к кому-то, кого ставишь ниже себя',
        агрессивность: 'гнев, направленный на то, что ещё только произойдёт',
        оптимизм: 'ожидание будущего вместе с радостью',
      }[d.name]
    }.`,
    key: `dyad:${d.name}`,
  }
}

function definition(rng: Rng, list: Word[]): Draft {
  const w = rng.pick(list)
  return {
    kind: 'choice',
    prompt: `Какое чувство описано так: «${w.def}»?`,
    ...withOptions(w.name, rng.shuffle(w.wrong), rng),
    hint: 'Вспомните ситуацию, когда вы это испытывали, и как вы её называли.',
    solution: `Это ${w.name}: ${w.def}.`,
    key: `def:${w.name}`,
  }
}

function pairTask(rng: Rng): Draft {
  const p = rng.pick(PAIRS)
  return {
    kind: 'choice',
    prompt: p.q,
    ...withOptions(p.right, rng.shuffle(p.wrong), rng),
    hint: 'Подумайте, на что направлено каждое чувство и что оно побуждает сделать.',
    solution: p.why,
    key: `pair:${p.q}`,
  }
}

function generate(level: Level, rng: Rng, index: number): Draft | null {
  switch (level) {
    case 1:
      return index % 2 === 0 ? strongest(rng) : family(rng)
    case 2:
      return [order, opposite, (r: Rng) => definition(r, COMMON.slice(0, 5))][index % 3](rng)
    case 3:
      return index % 3 === 2 ? dyad(rng, false) : definition(rng, COMMON)
    case 4:
      return index % 2 === 0 ? definition(rng, COMPLEX) : dyad(rng, index % 4 === 3)
    case 5:
      return index % 2 === 0 ? pairTask(rng) : definition(rng, SUBTLE)
  }
}

export const emotionsGenerator: ModuleGenerator = {
  module: 'emotions',
  targets: { 1: 8, 2: 8, 3: 8, 4: 8, 5: 8 },
  make: generate,
}

export function emotions(): Task[] {
  return collect(emotionsGenerator)
}

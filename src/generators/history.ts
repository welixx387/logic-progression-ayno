function year(level: Level, rng: Rng): Draft {
  const [event, y] = rng.pick(EVENTS[level])
  return {
    kind: 'number',
    prompt: `В каком году произошло событие: ${event}?`,
    answer: String(y),
    hint: 'Вспомните, при каком правителе это было, и соседние по времени события.',
    solution: `${event} — ${y} год.`,
    key: `year:${event}`,
  }
}

function earliest(level: Level, rng: Rng): Draft | null {
  const picked: Event[] = []
  for (const e of rng.shuffle(EVENTS[level])) {
    if (picked.every((p) => Math.abs(p[1] - e[1]) >= 2)) picked.push(e)
    if (picked.length === 4) break
  }
  if (picked.length < 4) return null
  const sorted = [...picked].sort((a, b) => a[1] - b[1])
  const first = sorted[0][0]
  return {
    kind: 'choice',
    prompt: 'Какое из этих событий произошло раньше остальных?',
    ...withOptions(first, picked.map((p) => p[0]), rng),
    hint: HINT,
    solution: sorted.map(([e, y]) => `${y} — ${e}`).join('\n'),
    key: `first:${sorted.map((p) => p[1]).join()}`,
  }
}

function ruler(level: Level, rng: Rng): Draft | null {
  const withRuler = EVENTS[level].filter((e) => e[2])
  const [event, y, who] = rng.pick(withRuler)
  const rulers = [...new Set([...EVENTS[level], ...EVENTS[Math.max(1, level - 1) as Level], ...EVENTS[Math.min(5, level + 1) as Level]].map((e) => e[2]).filter((r): r is string => !!r))]
  return {
    kind: 'choice',
    prompt: `${level >= 4 ? 'Кто руководил страной' : 'Кто правил Россией'}, когда произошло событие: ${event} (${y})?`,
    ...withOptions(who!, rng.shuffle(rulers), rng),
    hint: HINT,
    solution: `${event} — ${y} год, ${level >= 4 ? 'страной руководил' : 'правил'} ${who}.`,
    key: `ruler:${event}`,
  }
}

function fact(level: Level, rng: Rng): Draft {
  const i = rng.int(0, FACTS[level].length - 1)
  return factDraft(FACTS[level][i], rng, `fact:${level}:${i}`, HINT)
}

function generate(level: Level, rng: Rng, index: number): Draft | null {
  return [year, earliest, ruler, fact][index % 4](level, rng)
}

export const historyGenerator: ModuleGenerator = {
  module: 'history',
  targets: { 1: 10, 2: 10, 3: 10, 4: 10, 5: 10 },
  make: generate,
}

export function history(): Task[] {
  return collect(historyGenerator)
}

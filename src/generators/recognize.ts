/**
 * Распознавание эмоций по ситуации. Сценарии написаны вручную; в тексте:
 * {N} — имя, {N_g} — имя в родительном падеже, {N_d} — в дательном,
 * {N_a} — в винительном,
 * {он|она} — вариант для мужского и женского рода.
 */

interface Person {
  n: string
  g: string
  d: string
  /** Винительный падеж: «Артёма», «Аню». */
  a: string
  female: boolean
}


function fill(text: string, p: Person): string {
  return text
    .replace(/\{N_g\}/g, p.g)
    .replace(/\{N_d\}/g, p.d)
    .replace(/\{N_a\}/g, p.a)
    .replace(/\{N\}/g, p.n)
    .replace(/\{([^{}|]*)\|([^{}|]*)\}/g, (_, m: string, f: string) => (p.female ? f : m))
}


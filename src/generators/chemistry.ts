function grade8(rng: Rng, t: number): Draft | null {
  if (t === 0) {
    const [sym, name] = rng.pick(ELEMENTS)
    const bySymbol = rng.chance(0.5)
    const others = ELEMENTS.filter(([s]) => s !== sym)
    return bySymbol
      ? { kind: 'choice', prompt: `Какой химический элемент обозначается символом ${sym}?`, ...withOptions(name, rng.shuffle(others.map((e) => e[1])), rng), hint: 'Вспомните таблицу Менделеева.', solution: `${sym} — ${name}.`, key: `sym:${sym}` }
      : { kind: 'choice', prompt: `Как обозначается химический элемент ${name}?`, ...withOptions(sym, rng.shuffle(others.map((e) => e[0])), rng), hint: 'Вспомните таблицу Менделеева.', solution: `${name[0].toUpperCase()}${name.slice(1)} — ${sym}.`, key: `name:${sym}` }
  }
  if (t === 1) {
    const [sym, name, z] = rng.pick(ELEMENTS)
    const what = rng.pick(['протонов в ядре', 'электронов'])
    return {
      kind: 'number',
      prompt: `Порядковый номер элемента ${name} (${sym}) в таблице Менделеева — ${z}. Сколько ${what} у нейтрального атома этого элемента?`,
      answer: String(z),
      hint: 'Порядковый номер равен заряду ядра.',
      solution: `Порядковый номер равен числу протонов в ядре, а в нейтральном атоме число электронов равно числу протонов: ${z}.`,
      key: `z:${sym}:${what}`,
    }
  }
  if (t === 2) {
    const x = rng.pick(COMPOUNDS)
    const m = mass(x)
    return {
      kind: 'number',
      prompt: `Вычислите относительную молекулярную массу ${x.f} (${x.name}). Относительные атомные массы: ${arList(x)}.`,
      answer: String(m),
      hint: 'Сложите атомные массы всех атомов в формуле с учётом индексов.',
      solution: `Mr(${x.f}) = ${Object.entries(x.parts).map(([e, k]) => (k > 1 ? `${k} · ${num(AR[e])}` : num(AR[e]))).join(' + ')} = ${num(m)}.`,
      key: `mr:${x.f}`,
    }
  }
  const [el, parts, v] = rng.pick(VALENCE)
  const f = fml(parts)
  return {
    kind: 'choice',
    prompt: `Какова валентность элемента ${el} (${ELEMENTS.find((e) => e[0] === el)?.[1] ?? el}) в соединении ${f}? Валентность кислорода — II.`,
    ...withOptions(ROMAN[v], rng.shuffle(ROMAN.slice(1).filter((r) => r !== ROMAN[v])), rng),
    hint: 'Общее число единиц валентности у обоих элементов одинаково.',
    solution: `У атомов кислорода всего ${parts[1][1]} · 2 = ${parts[1][1] * 2} ${plural(parts[1][1] * 2, 'единица', 'единицы', 'единиц')} валентности. Столько же у ${parts[0][1] > 1 ? `${parts[0][1]} атомов ${el}` : `атома ${el}`}: ${parts[1][1] * 2} : ${parts[0][1]} = ${v}. Валентность ${ROMAN[v]}.`,
    key: `val:${f}`,
  }
}


function grade9(rng: Rng, t: number): Draft | null {
  if (t === 0) {
    const x = rng.pick(COMPOUNDS.filter((y) => Number.isInteger(mass(y))))
    const nMol = rng.pick([0.5, 1, 2, 3, 4, 5, 0.2])
    const m = mass(x) * nMol
    return {
      kind: 'number',
      prompt: `Какое количество вещества (моль) содержится в ${num(m)} г ${x.f} (${x.name})? Относительные атомные массы: ${arList(x)}.`,
      answer: String(nMol),
      hint: 'n = m / M, где M — молярная масса (г/моль).',
      solution: `M(${x.f}) = ${mass(x)} г/моль. n = ${num(m)} / ${mass(x)} = ${num(nMol)} моль.`,
      key: `mol:${x.f}:${nMol}`,
    }
  }
  if (t === 1) {
    const [el, name] = rng.pick(FRACTIONS)
    const x = COMPOUNDS.find((y) => y.name === name)!
    const w = (AR[el] * x.parts[el] * 100) / mass(x)
    return {
      kind: 'number',
      prompt: `Вычислите массовую долю (%) элемента ${el} в ${x.f} (${x.name}). Относительные атомные массы: ${arList(x)}.`,
      answer: String(Math.round(w * 10) / 10),
      hint: 'ω = Ar · (число атомов) / Mr · 100%.',
      solution: `Mr(${x.f}) = ${num(mass(x))}. ω(${el}) = ${AR[el]} · ${x.parts[el]} / ${num(mass(x))} · 100% = ${num(Math.round(w * 10) / 10)}%.`,
      key: `w:${el}:${x.f}`,
    }
  }
  if (t === 2) {
    const gas = rng.pick(['кислорода', 'водорода', 'азота', 'углекислого газа', 'метана'])
    const nMol = rng.pick([0.5, 1, 2, 3, 5, 10, 0.25])
    return {
      kind: 'number',
      prompt: `Какой объём (л) при нормальных условиях занимают ${num(nMol)} моль ${gas}?`,
      answer: String(Math.round(nMol * 22.4 * 100) / 100),
      hint: 'Один моль любого газа при нормальных условиях занимает 22,4 л.',
      solution: `V = n · 22,4 = ${num(nMol)} · 22,4 = ${num(Math.round(nMol * 22.4 * 100) / 100)} л.`,
      key: `gas:${gas}:${nMol}`,
    }
  }
  const solute = rng.pick([5, 10, 15, 20, 25, 30, 40, 50])
  const total = rng.pick([100, 200, 250, 400, 500])
  if (solute >= total) return null
  const w = (solute * 100) / total
  if (!Number.isInteger(w * 10)) return null
  return {
    kind: 'number',
    prompt: `В ${total - solute} г воды растворили ${solute} г соли. Какова массовая доля соли в растворе (%)?`,
    answer: String(w),
    hint: 'Массовая доля = масса вещества / масса раствора. Масса раствора = вода + соль.',
    solution: `Масса раствора: ${total - solute} + ${solute} = ${total} г. ω = ${solute} / ${total} · 100% = ${num(w)}%.`,
    key: `sol:${solute}:${total}`,
  }
}


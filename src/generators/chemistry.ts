function grade11(rng: Rng, t: number): Draft | null {
  if (t === 0) {
    const [el, parts, ox] = rng.pick(OX)
    // Проверяем табличное значение расчётом: сумма степеней окисления равна нулю.
    const known = parts.filter(([e]) => e !== el).reduce((s, [e, k]) => s + KNOWN[e] * k, 0)
    const count = parts.find(([e]) => e === el)![1]
    if (-known / count !== ox) throw new Error(`Степень окисления ${el} в ${fml(parts)} посчитана неверно`)
    const f = fml(parts)
    const opts = [-4, -3, -2, -1, 1, 2, 3, 4, 5, 6, 7].filter((x) => x !== ox).map(sign)
    return {
      kind: 'choice',
      prompt: `Какова степень окисления ${el} в ${f}?`,
      ...withOptions(sign(ox), rng.shuffle(opts), rng),
      hint: 'Сумма степеней окисления в молекуле равна нулю. H: +1, O: −2, K и Na: +1.',
      solution: `Сумма степеней окисления остальных атомов: ${parts
        .filter(([e]) => e !== el)
        .map(([e, k]) => `${k > 1 ? `${k} · ` : ''}(${sign(KNOWN[e])})`)
        .join(' + ')} = ${sign(known)}. Значит, на ${count > 1 ? `${count} атома ${el}` : el} приходится ${sign(-known)}: степень окисления ${sign(ox)}.`,
      key: `ox:${f}`,
    }
  }
  if (t === 1) {
    const i = rng.int(0, REACTIONS.length - 1)
    return factDraft(REACTIONS[i], rng, `react:${i}`, 'Сравните, сколько веществ вступает в реакцию и сколько образуется.')
  }
  const r = rng.int(0, 2)
  const k = rng.int(1, 5)
  if (r === 0) {
    const m = 12 * k
    return {
      kind: 'number',
      prompt: `Сколько граммов углекислого газа образуется при полном сгорании ${m} г углерода? C + O₂ → CO₂. Ar: C = 12, O = 16.`,
      answer: String(44 * k),
      hint: 'Найдите количество вещества углерода, по уравнению столько же моль CO₂.',
      solution: `n(C) = ${m} / 12 = ${k} моль. n(CO₂) = n(C) = ${k} моль. m(CO₂) = ${k} · 44 = ${44 * k} г.`,
      key: `st:c:${k}`,
    }
  }
  if (r === 1) {
    const m = 100 * k
    return {
      kind: 'number',
      prompt: `Сколько граммов оксида кальция получится при разложении ${m} г карбоната кальция? CaCO₃ → CaO + CO₂. Ar: Ca = 40, C = 12, O = 16.`,
      answer: String(56 * k),
      hint: 'M(CaCO₃) = 100 г/моль, M(CaO) = 56 г/моль. Моль к молю — один к одному.',
      solution: `n(CaCO₃) = ${m} / 100 = ${k} моль, n(CaO) = ${k} моль. m(CaO) = ${k} · 56 = ${56 * k} г.`,
      key: `st:caco3:${k}`,
    }
  }
  const m = 2 * k
  return {
    kind: 'number',
    prompt: `Сколько граммов воды образуется при сгорании ${m} г водорода? 2H₂ + O₂ → 2H₂O. Ar: H = 1, O = 16.`,
    answer: String(18 * k),
    hint: 'По уравнению из 2 моль H₂ получается 2 моль H₂O — то есть моль на моль.',
    solution: `n(H₂) = ${m} / 2 = ${k} моль, n(H₂O) = ${k} моль. m(H₂O) = ${k} · 18 = ${18 * k} г.`,
    key: `st:h2:${k}`,
  }
}

const GRADES = [(rng: Rng) => grade7(rng), grade8, grade9, grade10, grade11]

function generate(level: Level, rng: Rng, index: number): Draft | null {
  return GRADES[level - 1](rng, index % 4)
}

export const chemistryGenerator: ModuleGenerator = {
  module: 'chemistry',
  targets: { 1: 8, 2: 8, 3: 8, 4: 8, 5: 8 },
  make: generate,
}

export function chemistry(): Task[] {
  return collect(chemistryGenerator)
}

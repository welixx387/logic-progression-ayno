function grade10(rng: Rng, t: number): Draft | null {
  if (t === 0) {
    const k = rng.int(1, 10)
    const byName = rng.chance(0.5)
    const others = ALKANES.map((_, i) => i + 1).filter((j) => j !== k)
    return byName
      ? { kind: 'choice', prompt: `Какова формула алкана ${ALKANES[k - 1]}?`, ...withOptions(alkane(k), rng.shuffle(others.map(alkane)), rng), hint: 'Общая формула алканов CₙH₂ₙ₊₂; число n подсказывает корень названия.', solution: `${ALKANES[k - 1][0].toUpperCase()}${ALKANES[k - 1].slice(1)} — ${k} ${k === 1 ? 'атом' : k < 5 ? 'атома' : 'атомов'} углерода: ${alkane(k)}.`, key: `alk:f:${k}` }
      : { kind: 'choice', prompt: `Как называется алкан ${alkane(k)}?`, ...withOptions(ALKANES[k - 1], rng.shuffle(others.map((j) => ALKANES[j - 1])), rng), hint: 'Посчитайте атомы углерода.', solution: `${k} ${k === 1 ? 'атом' : k < 5 ? 'атома' : 'атомов'} углерода — ${ALKANES[k - 1]}.`, key: `alk:n:${k}` }
  }
  if (t === 1) {
    const k = rng.int(1, 10)
    return {
      kind: 'number',
      prompt: `Найдите молярную массу (г/моль) алкана ${ALKANES[k - 1]} (${alkane(k)}). Ar: C = 12, H = 1.`,
      answer: String(14 * k + 2),
      hint: 'M = 12 · (число атомов C) + 1 · (число атомов H).',
      solution: `M = 12 · ${k} + ${2 * k + 2} = ${14 * k + 2} г/моль.`,
      key: `alkM:${k}`,
    }
  }
  const i = rng.int(0, CLASSES.length - 1)
  return factDraft(CLASSES[i], rng, `org:${i}`, 'Вспомните классы органических веществ.')
}


function author(level: Level, rng: Rng): Draft {
  const work = rng.pick(WORKS[level])
  const authors = [...new Set(ALL.map((x) => x.author))]
  return {
    kind: 'choice',
    prompt: `Кто автор произведения ${work.title}?`,
    ...withOptions(work.author, rng.shuffle(authors), rng),
    hint: HINT,
    solution: `Автор произведения ${work.title} — ${work.author}.`,
    key: `author:${work.title}`,
  }
}

function hero(level: Level, rng: Rng): Draft {
  const work = rng.pick(WORKS[level].filter((x) => x.hero))
  const titles = rng.shuffle([...WORKS[level], ...ALL].filter((x) => x.hero).map((x) => x.title))
  return {
    kind: 'choice',
    prompt: `В каком произведении есть персонаж ${work.hero}?`,
    ...withOptions(work.title, titles, rng),
    hint: HINT,
    solution: `${work.hero![0].toUpperCase()}${work.hero!.slice(1)} — персонаж произведения ${work.title} (${work.author}).`,
    key: `hero:${work.title}`,
  }
}

function genre(level: Level, rng: Rng): Draft {
  const work = rng.pick(WORKS[level].filter((x) => x.genre))
  const close = GENRE_GROUPS.find((g) => g.includes(work.genre!)) ?? []
  const others = [...new Set(ALL.map((x) => x.genre).filter((g): g is string => !!g && !close.includes(g)))]
  const cap = (s: string) => s[0].toUpperCase() + s.slice(1)
  return {
    kind: 'choice',
    prompt: `К какому жанру относится ${work.title} (${work.author})?`,
    ...withOptions(cap(work.genre!), rng.shuffle(others).map(cap), rng),
    hint: 'Вспомните объём, род литературы (эпос, лирика, драма) и то, как назвал произведение сам автор.',
    solution: `${work.title} — ${work.genre}.`,
    key: `genre:${work.title}`,
  }
}

function fact(level: Level, rng: Rng): Draft {
  if (level === 5 && rng.chance(0.6)) {
    const [poet, movement] = rng.pick(MOVEMENTS)
    const all = [...new Set(MOVEMENTS.map((m) => m[1]))]
    return {
      kind: 'choice',
      prompt: `С каким литературным течением Серебряного века связано имя поэта ${poet}?`,
      ...withOptions(movement, rng.shuffle(all), rng),
      hint: HINT,
      solution: `${poet} — ${movement.toLowerCase()}.`,
      key: `movement:${poet}`,
    }
  }
  const i = rng.int(0, FACTS[level].length - 1)
  return factDraft(FACTS[level][i], rng, `fact:${level}:${i}`, HINT)
}

function generate(level: Level, rng: Rng, index: number): Draft | null {
  return [author, hero, genre, fact][index % 4](level, rng)
}

export const literatureGenerator: ModuleGenerator = {
  module: 'literature',
  targets: { 1: 10, 2: 10, 3: 10, 4: 10, 5: 10 },
  make: generate,
}

export function literature(): Task[] {
  return collect(literatureGenerator)
}

function correlation(level: Level, rng: Rng, index: number): Draft | null {
  if (index % 2 === 0 || level === 1) return correlationMaker(level, rng, index)
  // Направление связи по данным.
  const n = 6
  const kind = rng.int(0, 2)
  const xs = Array.from({ length: n }, (_, i) => (i + 1) * rng.int(2, 5))
  const ys = xs.map((x) => (kind === 0 ? 10 + x * 2 + rng.int(-3, 3) : kind === 1 ? 80 - x * 2 + rng.int(-3, 3) : rng.int(20, 60)))
  const mx = sum(xs) / n
  const my = sum(ys) / n
  const cov = sum(xs.map((x, i) => (x - mx) * (ys[i] - my)))
  const r = cov / Math.sqrt(sum(xs.map((x) => (x - mx) ** 2)) * sum(ys.map((y) => (y - my) ** 2)))
  const label = r > 0.6 ? 'Положительная: чем больше X, тем больше Y' : r < -0.6 ? 'Отрицательная: чем больше X, тем меньше Y' : 'Заметной связи нет'
  const display = { type: 'table' as const, head: ['Часы подготовки (X)', 'Ошибок / баллов (Y)'], rows: xs.map((x, i) => [String(x), String(ys[i])]) }
  return choice(
    'По таблице определите, какая связь между X и Y.',
    label,
    ['Положительная: чем больше X, тем больше Y', 'Отрицательная: чем больше X, тем меньше Y', 'Заметной связи нет'].filter((x) => x !== label),
    rng,
    'Смотрите, как меняется Y, когда X растёт: растёт, падает или прыгает без системы.',
    [`Коэффициент корреляции r ≈ ${dec(r, 2)}.`, r > 0.6 ? 'Y растёт вместе с X — связь положительная.' : r < -0.6 ? 'Y уменьшается при росте X — связь отрицательная.' : 'Y меняется без понятного направления — сильной связи нет.', 'Помните: даже сильная связь ещё не доказывает, что X — причина Y.'],
    `n:${xs.join(',')}:${ys.join(',')}`,
    { display, ref: 0 },
    3,
  )
}

// ——— Парадокс Симпсона ———

function simpson(level: Level, rng: Rng, index: number): Draft | null {
  // Ищем данные, где A лучше в каждой группе, но хуже в сумме.
  for (let attempt = 0; attempt < 400; attempt++) {
    const a1n = rng.int(2, 10) * 10
    const a2n = rng.int(10, 40) * 10
    const b1n = rng.int(10, 40) * 10
    const b2n = rng.int(2, 10) * 10
    const a1 = Math.round(a1n * rng.int(80, 98) / 100)
    const b1 = Math.round(b1n * rng.int(70, 95) / 100)
    const a2 = Math.round(a2n * rng.int(40, 70) / 100)
    const b2 = Math.round(b2n * rng.int(30, 65) / 100)
    const r = (x: number, n: number) => x / n
    if (!(r(a1, a1n) > r(b1, b1n) && r(a2, a2n) > r(b2, b2n))) continue
    const aAll = (a1 + a2) / (a1n + a2n)
    const bAll = (b1 + b2) / (b1n + b2n)
    if (!(aAll < bAll - 0.03)) continue
    const pct = (x: number) => Math.round(x * 1000) / 10
    const display = {
      type: 'table' as const,
      head: ['', 'Больница А', 'Больница Б'],
      rows: [
        ['Лёгкие случаи', `${a1} из ${a1n}`, `${b1} из ${b1n}`],
        ['Тяжёлые случаи', `${a2} из ${a2n}`, `${b2} из ${b2n}`],
        ['Всего', `${a1 + a2} из ${a1n + a2n}`, `${b1 + b2} из ${b1n + b2n}`],
      ],
    }
    const head = 'Число выздоровевших пациентов в двух больницах.'
    const t = level <= 2 ? index % 2 : index % 3
    if (t === 0)
      return numeric(`${head} Какой процент пациентов выздоровел в больнице А в целом? Ответ округлите до десятых.`, pct(aAll), 'Сложите выздоровевших и всех пациентов по обеим группам.', [`(${a1} + ${a2}) : (${a1n} + ${a2n}) = ${a1 + a2} : ${a1n + a2n} ≈ ${dec(pct(aAll), 1)}%.`], `a:${a1}/${a1n}:${a2}/${a2n}:${b1}/${b1n}:${b2}/${b2n}`, { display, ref: 0 })
    if (t === 1)
      return numeric(`${head} Какой процент тяжёлых пациентов выздоровел в больнице А? Ответ округлите до десятых.`, pct(a2 / a2n), 'Считайте только внутри группы тяжёлых случаев.', [`${a2} : ${a2n} ≈ ${dec(pct(a2 / a2n), 1)}%. В больнице Б: ${b2} : ${b2n} ≈ ${dec(pct(b2 / b2n), 1)}%.`], `h:${a1}/${a1n}:${a2}/${a2n}:${b1}/${b1n}:${b2}/${b2n}`, { display, ref: 0 })
    return choice(
      `${head} Какой вывод верный?`,
      'А лечит лучше: в каждой группе у неё выше доля выздоровевших, а в целом её результат хуже, потому что к ней чаще попадают тяжёлые больные',
      ['Б лечит лучше: в целом у неё выше доля выздоровевших', 'Больницы лечат одинаково', 'Данных недостаточно, чтобы сравнивать группы'],
      rng,
      'Сравните больницы отдельно для лёгких и для тяжёлых случаев, а потом — состав пациентов.',
      [`Лёгкие: А ${dec(pct(a1 / a1n), 1)}% против Б ${dec(pct(b1 / b1n), 1)}%. Тяжёлые: А ${dec(pct(a2 / a2n), 1)}% против Б ${dec(pct(b2 / b2n), 1)}%.`, `В целом: А ${dec(pct(aAll), 1)}%, Б ${dec(pct(bAll), 1)}%.`, `В А тяжёлых ${a2n} из ${a1n + a2n}, в Б — ${b2n} из ${b1n + b2n}. Итог искажён составом групп — это парадокс Симпсона.`],
      `c:${a1}/${a1n}:${a2}/${a2n}:${b1}/${b1n}:${b2}/${b2n}`,
      { display, ref: 0 },
    )
  }
  return null
}


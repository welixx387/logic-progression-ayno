/** Набор с целым средним и целым стандартным отклонением: подбираем отклонения от среднего. */
function niceSet(rng: Rng, n: number): { xs: number[]; mean: number; sd: number } | null {
  for (let attempt = 0; attempt < 200; attempt++) {
    const dev = Array.from({ length: n - 1 }, () => rng.int(-6, 6))
    dev.push(-sum(dev))
    if (Math.abs(dev[n - 1]) > 8) continue
    const v = sum(dev.map((d) => d * d)) / n
    const sd = Math.sqrt(v)
    if (!Number.isInteger(sd) || sd === 0) continue
    const mean = rng.int(10, 40)
    return { xs: dev.map((d) => mean + d), mean, sd }
  }
  return null
}

function spread(level: Level, rng: Rng, index: number): Draft | null {
  const t = level === 1 ? 0 : level === 2 ? index % 2 : level === 3 ? 1 + (index % 2) : level === 4 ? 2 + (index % 2) : 3
  if (t === 0) {
    const xs = Array.from({ length: rng.int(5, 8) }, () => rng.int(10, 60))
    return numeric(`Результаты прыжков в длину (см): ${xs.join(', ')}. Найдите размах — разницу между наибольшим и наименьшим значением.`, Math.max(...xs) - Math.min(...xs), 'Размах = максимум − минимум.', [`Наибольшее ${Math.max(...xs)}, наименьшее ${Math.min(...xs)}.`, `Размах: ${Math.max(...xs)} − ${Math.min(...xs)} = ${Math.max(...xs) - Math.min(...xs)}.`], `r:${xs.join(',')}`, { ref: 0 })
  }
  if (t === 1) {
    const mean = rng.int(20, 50)
    const a = Array.from({ length: 5 }, () => mean + rng.int(-3, 3))
    const b = Array.from({ length: 5 }, () => mean + rng.int(-12, 12))
    const ra = Math.max(...a) - Math.min(...a)
    const rb = Math.max(...b) - Math.min(...b)
    if (ra === rb) return null
    const stable = ra < rb ? 'Первый' : 'Второй'
    return choice(`Два спортсмена сделали по пять бросков (очки): первый — ${a.join(', ')}; второй — ${b.join(', ')}. Чьи результаты стабильнее?`, `${stable} спортсмен`, [`${stable === 'Первый' ? 'Второй' : 'Первый'} спортсмен`, 'Одинаково стабильны'], rng, 'Стабильность — это маленький разброс. Сравните размахи.', [`Размах у первого: ${Math.max(...a)} − ${Math.min(...a)} = ${ra}; у второго: ${Math.max(...b)} − ${Math.min(...b)} = ${rb}.`, `Меньший разброс — у того, чей размах меньше: ${stable.toLowerCase()} спортсмен.`], `c:${a.join(',')}:${b.join(',')}`, { ref: 0 }, 3)
  }
  const set = niceSet(rng, level >= 4 ? 6 : 4)
  if (!set) return null
  const { xs, mean, sd } = set
  if (t === 2) {
    const v = sd * sd
    return numeric(`Найдите дисперсию набора: ${xs.join(', ')}. (Дисперсия — среднее квадратов отклонений от среднего.)`, v, 'Сначала найдите среднее, затем отклонения каждого числа, их квадраты и среднее этих квадратов.', [`Среднее: ${sum(xs)} : ${xs.length} = ${mean}.`, `Отклонения: ${xs.map((x) => dec(x - mean)).join(', ')}; квадраты: ${xs.map((x) => (x - mean) ** 2).join(', ')}.`, `Дисперсия: ${sum(xs.map((x) => (x - mean) ** 2))} : ${xs.length} = ${v}.`], `v:${xs.join(',')}`, { ref: 1 })
  }
  return numeric(`Найдите стандартное отклонение набора: ${xs.join(', ')}.`, sd, 'Стандартное отклонение — квадратный корень из дисперсии.', [`Среднее: ${sum(xs)} : ${xs.length} = ${mean}.`, `Квадраты отклонений: ${xs.map((x) => (x - mean) ** 2).join(', ')}; их среднее (дисперсия): ${sum(xs.map((x) => (x - mean) ** 2))} : ${xs.length} = ${sd * sd}.`, `Стандартное отклонение: √${sd * sd} = ${sd}.`], `s:${xs.join(',')}`, { ref: 1 })
}


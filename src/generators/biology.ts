const facts = (level: Level, rng: Rng) => {
  const i = rng.int(0, FACTS[level].length - 1)
  return factDraft(FACTS[level][i], rng, `fact:${level}:${i}`, HINT)
}

function generate(level: Level, rng: Rng, index: number): Draft | null {
  const t = index % 4
  if (level === 4) return [facts, () => monohybrid(rng), () => chargaff(rng), () => chromosomes(rng)][t](level, rng)
  if (level === 5) return [facts, () => tenPercent(rng), facts, () => dihybrid(rng)][t](level, rng)
  return facts(level, rng)
}


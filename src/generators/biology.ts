const CHAINS = [
  ['трава', 'кузнечик', 'лягушка', 'уж', 'орёл'],
  ['зерно', 'мышь', 'змея', 'ястреб'],
  ['фитопланктон', 'зоопланктон', 'сельдь', 'тюлень'],
  ['листья', 'гусеница', 'синица', 'ястреб'],
  ['трава', 'заяц', 'лиса'],
] as const

function tenPercent(rng: Rng): Draft {
  const chain = rng.pick(CHAINS)
  const top = chain.length - 1
  const mass = rng.pick([1, 2, 3, 4, 5, 6, 8, 10, 12, 15])
  const producers = mass * 10 ** top
  const up = rng.chance(0.5)
  const steps = Array.from({ length: top }, (_, i) => `${mass * 10 ** (top - i)} → ${mass * 10 ** (top - i - 1)}`)
  return up
    ? {
        kind: 'number',
        prompt: `Цепь питания: ${chain.join(' → ')}. Сколько килограммов продуцентов (${chain[0]}) нужно, чтобы вырос${chain[top] === 'лиса' || chain[top] === 'змея' ? 'ла' : ''} ${chain[top]} массой ${mass} кг? Используйте правило 10%.`,
        answer: String(producers),
        hint: 'На каждый следующий уровень переходит около 10% энергии (массы), поэтому вниз по цепи масса растёт в 10 раз.',
        solution: `${capitalize(chain[top])} — ${top}-й уровень после продуцентов. ${mass} · 10${'⁰¹²³⁴'[top]} = ${producers} кг.`,
        key: `eco-up:${chain.join()}:${mass}`,
      }
    : {
        kind: 'number',
        prompt: `Цепь питания: ${chain.join(' → ')}. Масса продуцентов (${chain[0]}) — ${producers} кг. Какую массу может набрать ${chain[top]} (в кг)? Используйте правило 10%.`,
        answer: String(mass),
        hint: 'На каждый следующий уровень переходит около 10% массы.',
        solution: `Каждый переход — в 10 раз меньше: ${steps.join(', ')} кг.`,
        key: `eco-down:${chain.join()}:${mass}`,
      }
}


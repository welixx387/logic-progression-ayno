/** Воинские звания по возрастанию. */
const RANKS = [
  'рядовой',
  'ефрейтор',
  'младший сержант',
  'сержант',
  'старший сержант',
  'старшина',
  'прапорщик',
  'старший прапорщик',
  'младший лейтенант',
  'лейтенант',
  'старший лейтенант',
  'капитан',
  'майор',
  'подполковник',
  'полковник',
  'генерал-майор',
  'генерал-лейтенант',
  'генерал-полковник',
  'генерал армии',
]

function ranks(rng: Rng): Draft {
  const picked = rng.shuffle(RANKS.map((_, i) => i)).slice(0, 4)
  const top = Math.max(...picked)
  const cap = (s: string) => s[0].toUpperCase() + s.slice(1)
  return {
    kind: 'choice',
    prompt: 'Какое из этих воинских званий самое высокое?',
    ...withOptions(cap(RANKS[top]), picked.filter((i) => i !== top).map((i) => cap(RANKS[i])), rng),
    hint: 'Порядок: рядовой → сержанты → прапорщики → лейтенанты → капитан → майор → подполковник → полковник → генералы.',
    solution: `По возрастанию: ${[...picked].sort((a, b) => a - b).map((i) => RANKS[i]).join(' → ')}.`,
    key: `ranks:${[...picked].sort((a, b) => a - b).join()}`,
  }
}

function fact(level: Level, rng: Rng): Draft {
  const i = rng.int(0, FACTS[level].length - 1)
  return factDraft(FACTS[level][i], rng, `fact:${level}:${i}`, HINT)
}

function generate(level: Level, rng: Rng, index: number): Draft | null {
  if (level === 4 && index % 2 === 1) return ranks(rng)
  return fact(level, rng)
}

export const safetyGenerator: ModuleGenerator = {
  module: 'safety',
  targets: { 1: 8, 2: 8, 3: 8, 4: 8, 5: 6 },
  make: generate,
}

export function safety(): Task[] {
  return collect(safetyGenerator)
}

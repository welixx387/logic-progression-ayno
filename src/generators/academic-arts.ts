// ——— Числительные ———

const DE_UNITS = ['', 'eins', 'zwei', 'drei', 'vier', 'fünf', 'sechs', 'sieben', 'acht', 'neun']
const DE_TEENS = ['zehn', 'elf', 'zwölf', 'dreizehn', 'vierzehn', 'fünfzehn', 'sechzehn', 'siebzehn', 'achtzehn', 'neunzehn']
const DE_TENS = ['', '', 'zwanzig', 'dreißig', 'vierzig', 'fünfzig', 'sechzig', 'siebzig', 'achtzig', 'neunzig']

function de(n: number): string {
  if (n >= 100) {
    const h = Math.floor(n / 100)
    return `${h === 1 ? 'ein' : DE_UNITS[h]}hundert${n % 100 ? de(n % 100) : ''}`
  }
  if (n < 10) return DE_UNITS[n]
  if (n < 20) return DE_TEENS[n - 10]
  const u = n % 10
  return u ? `${u === 1 ? 'ein' : DE_UNITS[u]}und${DE_TENS[Math.floor(n / 10)]}` : DE_TENS[Math.floor(n / 10)]
}

const FR_UNITS = ['', 'un', 'deux', 'trois', 'quatre', 'cinq', 'six', 'sept', 'huit', 'neuf', 'dix', 'onze', 'douze', 'treize', 'quatorze', 'quinze', 'seize']
const FR_TENS = ['', 'dix', 'vingt', 'trente', 'quarante', 'cinquante', 'soixante']

function fr(n: number): string {
  if (n >= 100) {
    const h = Math.floor(n / 100)
    const rest = n % 100
    const head = h === 1 ? 'cent' : `${FR_UNITS[h]} cent${rest ? '' : 's'}`
    return rest ? `${head} ${fr(rest)}` : head
  }
  if (n <= 16) return FR_UNITS[n]
  if (n < 20) return `dix-${FR_UNITS[n - 10]}`
  if (n < 70) {
    const t = Math.floor(n / 10)
    const u = n % 10
    return u === 0 ? FR_TENS[t] : u === 1 ? `${FR_TENS[t]} et un` : `${FR_TENS[t]}-${FR_UNITS[u]}`
  }
  if (n < 80) return n === 71 ? 'soixante et onze' : `soixante-${fr(n - 60)}`
  if (n === 80) return 'quatre-vingts'
  return `quatre-vingt-${fr(n - 80)}`
}

/** Вопрос «как записать число словами»: неверные варианты — соседние числа и перестановка цифр. */
function numberWord(lang: 'de' | 'fr', rng: Rng, lo: number, hi: number): Draft | null {
  const n = rng.int(lo, hi)
  const word = lang === 'de' ? de : fr
  const swap = n < 100 && n % 10 !== 0 && n % 10 !== Math.floor(n / 10) ? (n % 10) * 10 + Math.floor(n / 10) : n + 10
  const near = [swap, n + 1, n - 1, n + 10, n - 10, n + 20].filter((x) => x > 0 && x !== n && x < 1000)
  const wrong = [...new Set(near.map(word))].filter((w) => w !== word(n))
  const lname = lang === 'de' ? 'по-немецки' : 'по-французски'
  const steps =
    lang === 'de'
      ? [`${n} = ${word(n)}.`, 'В немецком единицы называют раньше десятков: 47 — siebenundvierzig, «семь и сорок».']
      : [`${n} = ${word(n)}.`, 'Во французском 70 — soixante-dix (60 + 10), 80 — quatre-vingts (4 × 20), 90 — quatre-vingt-dix (4 × 20 + 10). В 21, 31, …, 71 пишут «et»: vingt et un.']
  return choice(`Как ${lname} число ${n}?`, word(n), rng.shuffle(wrong), rng, lang === 'de' ? 'Сначала единицы, потом «und» и десятки.' : 'Разложите число: 70 = 60 + 10, 80 = 4 × 20, 90 = 4 × 20 + 10.', steps, `${lang}:${n}`)
}


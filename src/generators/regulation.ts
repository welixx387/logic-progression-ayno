const ALL = [L1, L2, L3, L4, L5]

function generate(level: Level, rng: Rng): Draft | null {
  const list = ALL[level - 1]
  const i = rng.int(0, list.length - 1)
  const c = list[i]
  return {
    kind: 'choice',
    prompt: `${c.text}\n\n${c.q ?? Q}`,
    ...withOptions(c.right, rng.shuffle(c.wrong), rng),
    hint: level >= 3 ? 'Спросите себя: можно ли повлиять на ситуацию? Если да — помогает действие, если нет — принятие и забота о себе.' : 'Какой вариант помогает и сейчас, и в долгосрочной перспективе, а не только «выпустить пар»?',
    solution: c.why,
    key: `reg:${level}:${i}`,
  }
}


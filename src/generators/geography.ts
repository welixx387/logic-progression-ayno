function density(rng: Rng): Draft {
  const area = rng.pick([50, 80, 100, 120, 200, 250, 300, 400, 500])
  const d = rng.pick([5, 10, 15, 20, 25, 40, 60, 80, 100, 120, 150, 200, 250, 300])
  const pop = (area * d) / 1000
  if (!Number.isInteger(pop * 10)) return density(rng)
  const popText = String(pop).replace('.', ',')
  return {
    kind: 'number',
    prompt: `Площадь страны — ${area} тыс. км², население — ${popText} млн человек. Какова средняя плотность населения (чел./км²)?`,
    answer: String(d),
    hint: 'Плотность = население : площадь. Переведите миллионы и тысячи в единицы.',
    solution: `${popText} млн = ${(pop * 1_000_000).toLocaleString('ru-RU')} чел., ${area} тыс. км² = ${(area * 1000).toLocaleString('ru-RU')} км². ${(pop * 1_000_000).toLocaleString('ru-RU')} : ${(area * 1000).toLocaleString('ru-RU')} = ${d} чел./км².`,
    key: `density:${area}:${d}`,
  }
}

function growth(rng: Rng): Draft {
  const births = rng.int(7, 40)
  const deaths = rng.int(5, 16)
  const g = births - deaths
  return {
    kind: 'number',
    prompt: `В стране рождаемость — ${births}‰, смертность — ${deaths}‰. Каков естественный прирост населения (в ‰)?`,
    answer: String(g),
    hint: 'Естественный прирост = рождаемость − смертность. ‰ — промилле, число на 1000 жителей.',
    solution: `${births} − ${deaths} = ${g}‰${g < 0 ? ': население сокращается (естественная убыль)' : ''}.`,
    key: `growth:${births}:${deaths}`,
  }
}

function urban(rng: Rng): Draft {
  const total = rng.pick([4, 5, 8, 10, 12, 16, 20, 25, 40, 50])
  const share = rng.pick([20, 25, 30, 40, 45, 60, 65, 70, 75, 80, 85, 90])
  const city = (total * share) / 100
  const cityText = String(city).replace('.', ',')
  return {
    kind: 'number',
    prompt: `В стране живёт ${total} млн человек, из них в городах — ${cityText} млн. Каков уровень урбанизации (в %)?`,
    answer: String(share),
    hint: 'Уровень урбанизации — доля городского населения в процентах.',
    solution: `${cityText} : ${total} · 100% = ${share}%.`,
    key: `urban:${total}:${share}`,
  }
}

function generate(level: Level, rng: Rng, index: number): Draft | null {
  const t = index % 4
  switch (level) {
    case 1:
      return [
        () => facts(1, rng),
        () => pair(rng, COUNTRY_CONTINENT, (c) => `На каком материке находится страна ${c}?`, (c, m) => `Страна ${c} расположена на материке ${m}.`, 'country'),
        () => pair(rng, PEAKS, (p) => `На каком материке находится высочайшая вершина ${p}?`, (p, m) => `${p} — высшая точка материка ${m}.`, 'peak'),
        () => pair(rng, RIVERS_WORLD, (r) => `На каком материке течёт река ${r}?`, (r, m) => `Река ${r} течёт по материку ${m}.`, 'river'),
      ][t]()
    case 2:
      return [
        () => facts(2, rng),
        () => pair(rng, RIVER_SEA, (r) => `В какое море впадает река ${r}?`, (r, s) => `${r} впадает в ${s.replace('море', '').trim()} море.`.replace('Море Лаптевых море', 'море Лаптевых'), 'river-sea'),
        () => pair(rng, SEA_OCEAN, (s) => `Бассейну какого океана принадлежит ${s.replace('Море', 'море')}?`, (s, o) => `${s} относится к бассейну: ${o}.`, 'sea'),
        () => pair(rng, ZONES, (z) => `Для какой природной зоны России характерны: ${z}?`, (z, n) => `${z[0].toUpperCase()}${z.slice(1)} — типичны для зоны «${n}».`, 'zone'),
      ][t]()
    case 3:
      return [
        () => facts(3, rng),
        () => pair(rng, REPUBLICS, (r) => `Какой город — столица республики ${r}?`, (r, c) => `Столица республики ${r} — ${c}.`, 'republic'),
        () => facts(3, rng),
        () => pair(rng, REPUBLICS, (r) => `Какой город — столица республики ${r}?`, (r, c) => `Столица республики ${r} — ${c}.`, 'republic'),
      ][t]()
    case 4:
      return [
        () => facts(4, rng),
        () => pair(rng, CAPITALS, (c) => `Какой город — столица страны ${c}?`, (c, x) => `Столица страны ${c} — ${x}.`, 'capital'),
        () => rng.pick([density, growth, urban])(rng),
        () => pair(rng, CAPITALS, (c) => `Какой город — столица страны ${c}?`, (c, x) => `Столица страны ${c} — ${x}.`, 'capital'),
      ][t]()
    default:
      return [
        () => facts(5, rng),
        () => pair(rng, LANGUAGES, (c) => `Какой язык — официальный в стране ${c}?`, (c, l) => `Официальный язык страны ${c} — ${l.toLowerCase()}.`, 'lang'),
        () => pair(rng, CURRENCIES, (c) => `Как называется валюта страны ${c}?`, (c, m) => `Валюта страны ${c} — ${m.toLowerCase()}.`, 'money'),
        () => pair(rng, RELIGIONS, (c) => `Какая религия преобладает в стране ${c}?`, (c, r) => `Большинство жителей страны ${c} исповедуют ${r.toLowerCase()}.`, 'faith'),
      ][t]()
  }
}


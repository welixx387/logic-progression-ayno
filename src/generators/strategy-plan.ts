const SMART_KINDS = ['Конкретность', 'Измеримость', 'Достижимость', 'Срок']

function smart(level: Level, rng: Rng, index: number): Draft | null {
  const g = rng.pick(GOALS)
  const i = GOALS.indexOf(g)
  const full = `${g.act[0].toUpperCase() + g.act.slice(1)} ${g.measure} ${g.deadline}.`
  const t = level === 1 ? index % 2 : level === 2 ? index % 3 : level === 3 ? 1 + (index % 3) : 2 + (index % 3)
  const notes = {
    Конкретность: 'Specific — понятно, что именно нужно сделать.',
    Измеримость: 'Measurable — есть число или признак, по которому видно, достигнута ли цель.',
    Достижимость: 'Achievable — цель реальна при ваших ресурсах и времени.',
    Срок: 'Time-bound — есть конкретный срок.',
    Значимость: 'Relevant — цель важна для вас и связана с большими планами.',
  } as Record<string, string>
  if (t === 0)
    return choice(`Цель: «${g.act[0].toUpperCase() + g.act.slice(1)} ${g.measure}». Какого критерия SMART не хватает?`, 'Срок', SMART_KINDS.filter((k) => k !== 'Срок'), rng, 'Проверьте по порядку: что сделать, сколько, реально ли, к какому сроку.', ['Всё конкретно и измеримо, но непонятно, к какому сроку. Без срока цель легко откладывать бесконечно.'], `d:${i}`, { notes, ref: 0 })
  if (t === 1)
    return choice(`Цель: «${g.vague}». Какого критерия SMART не хватает в первую очередь?`, 'Измеримость', ['Срок', 'Достижимость', 'Значимость'], rng, 'Как вы поймёте, что цель достигнута?', [`«${g.vague}» — неясно, как проверить результат. Нужна мера, например: «${full.slice(0, -1)}».`, 'Срока тоже нет, но без измеримости даже срок не поможет понять, выполнена ли цель.'], `v:${i}`, { notes, ref: 0 })
  if (t === 2)
    return choice(`Цель: «${g.unreal}». Какой критерий SMART нарушен?`, 'Достижимость', ['Измеримость', 'Срок', 'Конкретность'], rng, 'Цель есть, число есть, срок есть. А реальна ли она?', ['Цель конкретная, измеримая и со сроком, но нереальная. Недостижимые цели демотивируют: провал заранее гарантирован.'], `u:${i}`, { notes, ref: 0 })
  const others = rng.sample(
    GOALS.filter((x) => x !== g),
    2,
  )
  return choice('Какая цель сформулирована по SMART лучше всего?', full, [g.vague + '.', others[0].unreal + '.', `${others[1].act[0].toUpperCase() + others[1].act.slice(1)} ${others[1].measure}.`], rng, 'Ищите цель, где есть и действие, и число, и срок, и которая реальна.', [`«${full.slice(0, -1)}» — конкретно (${g.act}), измеримо (${g.measure}), реально и со сроком (${g.deadline}).`, 'Остальные: расплывчатая, нереальная или без срока.'], `b:${i}:${others.map((o) => GOALS.indexOf(o)).join(',')}`, { ref: 0 })
}


// ——— Распределение задач ———

const WORKERS = ['Аня', 'Борис', 'Вера', 'Глеб']
const JOBS = ['Сайт', 'Логотип', 'Текст', 'Видео']

function perms(n: number): number[][] {
  if (n === 1) return [[0]]
  return perms(n - 1).flatMap((p) => Array.from({ length: n }, (_, i) => [...p.slice(0, i), n - 1, ...p.slice(i)]))
}

function assignment(level: Level, rng: Rng, index: number): Draft | null {
  const n = level <= 2 ? 3 : 4
  const hours = Array.from({ length: n }, () => Array.from({ length: n }, () => rng.int(level <= 2 ? 2 : 3, level <= 2 ? 9 : 15)))
  const all = perms(n).map((p) => ({ p, total: p.reduce((s, j, i) => s + hours[i][j], 0) }))
  all.sort((a, b) => a.total - b.total)
  if (all[0].total === all[1].total) return null
  const best = all[0]
  // Жадный выбор (каждый берёт свою самую быструю свободную задачу) должен ошибаться на высоких уровнях.
  const greedy: number[] = []
  for (let i = 0; i < n; i++) {
    const free = Array.from({ length: n }, (_, j) => j).filter((j) => !greedy.includes(j))
    greedy.push(free.reduce((b, j) => (hours[i][j] < hours[i][b] ? j : b), free[0]))
  }
  const greedyTotal = greedy.reduce((s, j, i) => s + hours[i][j], 0)
  if (level >= 3 && greedyTotal === best.total) return null
  const display = { type: 'table' as const, head: ['Исполнитель', ...JOBS.slice(0, n)], rows: WORKERS.slice(0, n).map((w, i) => [w, ...hours[i].map(String)]) }
  const plan = best.p.map((j, i) => `${WORKERS[i]} — ${JOBS[j].toLowerCase()} (${hours[i][j]} ч)`).join(', ')
  const steps = [`Перебираем все распределения (их ${all.length}) и считаем сумму часов.`, `Лучшее: ${plan} — всего ${best.total} ч.`, level >= 3 ? `Если каждый по очереди берёт свою самую быструю свободную задачу, получится ${greedyTotal} ч — жадный выбор не оптимален.` : '']
  if (index % 2 === 0 || level === 1)
    return numeric(`В таблице — сколько часов нужно каждому на каждую задачу. Каждый делает ровно одну задачу, каждую задачу — ровно один. Какое наименьшее суммарное время работы?`, best.total, 'Попробуйте разные распределения. Начните с самых «дорогих» задач: кому они обходятся дешевле всего?', steps.filter(Boolean), `t:${hours.flat().join(',')}`, { display, ref: 0 })
  const who = rng.int(0, n - 1)
  return choice(`В таблице — сколько часов нужно каждому на каждую задачу. Каждый делает ровно одну задачу. Какую задачу получит ${WORKERS[who]} в лучшем (самом быстром в сумме) распределении?`, JOBS[best.p[who]], JOBS.slice(0, n).filter((_, j) => j !== best.p[who]), rng, 'Лучшее распределение минимизирует сумму, а не время каждого по отдельности.', steps.filter(Boolean), `w:${hours.flat().join(',')}:${who}`, { display, ref: 0 }, Math.min(4, n))
}

// ——— Порядок выполнения ———

const CLIENTS = ['Ира', 'Кирилл', 'Лена', 'Миша', 'Надя', 'Олег', 'Паша']

function scheduling(level: Level, rng: Rng, index: number): Draft | null {
  const n = level + 2
  const names = CLIENTS.slice(0, n)
  const dur = names.map(() => rng.int(1, 12))
  if (new Set(dur).size < n) return null
  const order = names.map((_, i) => i).sort((a, b) => dur[a] - dur[b])
  let t = 0
  let totalWait = 0
  const log: string[] = []
  for (const i of order) {
    totalWait += t
    log.push(`${names[i]} ждёт ${t} мин`)
    t += dur[i]
  }
  const display = { type: 'table' as const, head: ['Клиент', 'Время работы, мин'], rows: names.map((c, i) => [c, String(dur[i])]) }
  if (level >= 4 && index % 2 === 1) {
    // Срочные заказы: сколько можно успеть вовремя при правильном порядке (по сроку).
    const due = names.map((_, i) => dur[i] + rng.int(0, 20))
    const byDue = names.map((_, i) => i).sort((a, b) => due[a] - due[b])
    // Алгоритм Мура: выбрасываем самый долгий заказ, если текущий опаздывает.
    const kept: number[] = []
    let time = 0
    for (const i of byDue) {
      kept.push(i)
      time += dur[i]
      if (time > due[i]) {
        const longest = kept.reduce((b, k) => (dur[k] > dur[b] ? k : b), kept[0])
        kept.splice(kept.indexOf(longest), 1)
        time -= dur[longest]
      }
    }
    const d2 = { type: 'table' as const, head: ['Заказчик', 'Работа, мин', 'Срок, мин от начала'], rows: names.map((c, i) => [c, String(dur[i]), String(due[i])]) }
    return numeric('Мастер выполняет заказы по одному. Какое наибольшее число заказов он может сдать вовремя (остальные — с опозданием)?', kept.length, 'Выполняйте заказы по возрастанию срока; если очередной опаздывает — откажитесь от самого долгого из взятых.', [`Сортируем по сроку: ${byDue.map((i) => names[i]).join(', ')}.`, 'Если очередной заказ не успевает, убираем из плана самый долгий из взятых — так освобождается больше всего времени (алгоритм Мура).', `Вовремя: ${kept.length} — ${kept.map((i) => names[i]).join(', ')}.`], `m:${dur.join(',')}:${due.join(',')}`, { display: d2, ref: 1 })
  }
  if (index % 2 === 0 || level === 1)
    return numeric(`В копицентр с одним аппаратом одновременно пришли ${n} ${plural(n, 'клиент', 'клиента', 'клиентов')}; время работы с каждым — в таблице. Обслуживать их можно в любом порядке. Каково наименьшее возможное суммарное время ожидания всех клиентов (в минутах)?`, totalWait, 'Короткие заказы — вперёд: тогда меньше людей ждёт долгих.', [`Порядок по возрастанию времени: ${order.map((i) => `${names[i]} (${dur[i]})`).join(', ')}.`, `${log.join(', ')}.`, `Сумма ожиданий: ${totalWait} мин. Это правило «сначала короткие» (SPT).`], `w:${dur.join(',')}`, { display, ref: 0 })
  return choice(`В копицентр с одним аппаратом одновременно пришли ${n} ${plural(n, 'клиент', 'клиента', 'клиентов')}; время работы с каждым — в таблице. Кого нужно обслужить первым, чтобы суммарное время ожидания всех было наименьшим?`, names[order[0]], names.filter((_, i) => i !== order[0]), rng, 'Кто задерживает остальных меньше всего?', [`Первым — тот, у кого самый короткий заказ: ${names[order[0]]} (${dur[order[0]]} мин).`, 'Каждая минута первого заказа прибавляется к ожиданию всех остальных, поэтому короткие — вперёд.'], `f:${dur.join(',')}`, { display, ref: 0 }, Math.min(4, n))
}

// ——— Маршрут ———

function routing(level: Level, rng: Rng): Draft | null {
  const n = level <= 2 ? 4 : 5
  const points = ['Склад', 'А', 'Б', 'В', 'Г'].slice(0, n)
  const d: number[][] = points.map(() => points.map(() => 0))
  for (let i = 0; i < n; i++)
    for (let j = i + 1; j < n; j++) {
      d[i][j] = d[j][i] = rng.int(2, 15)
    }
  const rest = perms(n - 1).map((p) => p.map((x) => x + 1))
  const routes = rest.map((p) => ({ p, len: d[0][p[0]] + p.slice(1).reduce((s, x, k) => s + d[p[k]][x], 0) + d[p[p.length - 1]][0] }))
  routes.sort((a, b) => a.len - b.len)
  // Каждый маршрут встречается дважды (в обе стороны) — нужен единственный лучший с точностью до направления.
  if (routes[2] && routes[2].len === routes[0].len) return null
  // Жадный «к ближайшему» — для сравнения.
  const greedy = [0]
  while (greedy.length < n) {
    const cur = greedy[greedy.length - 1]
    const next = points.map((_, i) => i).filter((i) => !greedy.includes(i)).reduce((b, i) => (d[cur][i] < d[cur][b] ? i : b), points.map((_, i) => i).find((i) => !greedy.includes(i))!)
    greedy.push(next)
  }
  const greedyLen = greedy.slice(1).reduce((s, x, k) => s + d[greedy[k]][x], 0) + d[greedy[n - 1]][0]
  if (level >= 4 && greedyLen === routes[0].len) return null
  const display = { type: 'table' as const, head: ['', ...points], rows: points.map((p, i) => [p, ...d[i].map((x, j) => (i === j ? '—' : String(x)))]) }
  const best = routes[0]
  return numeric(
    'Курьер выезжает со склада, должен побывать в каждом пункте по одному разу и вернуться. Расстояния (км) — в таблице. Какова длина самого короткого маршрута?',
    best.len,
    'Переберите порядки объезда: их немного. Не доверяйте правилу «всегда к ближайшему».',
    [`Лучший маршрут: Склад → ${best.p.map((x) => points[x]).join(' → ')} → Склад = ${best.len} км.`, `Всего маршрутов ${routes.length / 2} (каждый можно проехать в обе стороны).`, greedyLen > best.len ? `Правило «всегда к ближайшему» даёт ${greedyLen} км — длиннее оптимального.` : `Правило «всегда к ближайшему» здесь тоже даёт ${best.len} км, но в общем случае оно может ошибаться.`, 'Это задача коммивояжёра: при большом числе пунктов её решают приближённо.'],
    `r:${d.flat().join(',')}`,
    { display, ref: 0 },
  )
}

// ——— Запасы ———

function inventory(level: Level, rng: Rng, index: number): Draft | null {
  const daily = rng.int(3, 30)
  const lead = rng.int(2, 10)
  const t = level === 1 ? 0 : level === 2 ? index % 2 : level === 3 ? 1 + (index % 2) : 2 + (index % 2)
  if (t === 0) {
    const stock = daily * rng.int(5, 30) + rng.int(0, daily - 1)
    const days = Math.floor(stock / daily)
    return numeric(`В кофейне ${stock} ${plural(stock, 'пачка', 'пачки', 'пачек')} молока, в день уходит ${daily}. На сколько полных дней хватит запаса?`, days, 'Разделите запас на расход в день и отбросьте остаток.', [`${stock} : ${daily} = ${days} (остаток ${stock - days * daily}).`, `Полных дней: ${days}.`], `d:${stock}:${daily}`, { ref: 0 })
  }
  if (t === 1)
    return numeric(`Магазин продаёт ${daily} ${plural(daily, 'упаковку', 'упаковки', 'упаковок')} воды в день. Поставщик привозит товар через ${lead} ${plural(lead, 'день', 'дня', 'дней')} после заказа. При каком остатке нужно делать заказ, чтобы вода не закончилась (без страхового запаса)?`, daily * lead, 'Пока едет заказ, продажи продолжаются.', [`За ${lead} ${plural(lead, 'день', 'дня', 'дней')} доставки продадут ${daily} · ${lead} = ${daily * lead}.`, `Заказывать нужно, когда остаётся ${daily * lead} — это точка перезаказа.`], `r:${daily}:${lead}`, { ref: 1 })
  if (t === 2) {
    const safety = rng.int(1, 4) * daily
    return numeric(`Магазин продаёт ${daily} ${plural(daily, 'упаковку', 'упаковки', 'упаковок')} в день, доставка идёт ${lead} ${plural(lead, 'день', 'дня', 'дней')}, а на случай задержки держат страховой запас: ${safety} ${plural(safety, 'упаковка', 'упаковки', 'упаковок')}. При каком остатке нужно делать заказ?`, daily * lead + safety, 'Точка заказа = расход за время доставки + страховой запас.', [`Расход за доставку: ${daily} · ${lead} = ${daily * lead}.`, `Плюс страховой запас: ${daily * lead} + ${safety} = ${daily * lead + safety}.`], `s:${daily}:${lead}:${safety}`, { ref: 1 })
  }
  // Оптимальный размер заказа (формула Уилсона) с «круглыми» числами.
  const q = rng.pick([100, 200, 300, 400, 500, 600, 800, 1000])
  const h = rng.pick([2, 4, 5, 10, 20])
  const s = rng.pick([50, 100, 200, 250, 500])
  const D = (q * q * h) / (2 * s)
  // Поставок в год должно быть разумное число: от 4 до 52.
  if (!Number.isInteger(D) || D / q < 4 || D / q > 52) return null
  return numeric(`За год продаётся ${big(D)} ${plural(D, 'единица', 'единицы', 'единиц')} товара. Одна поставка стоит ${s} ₽ (независимо от объёма), хранение единицы товара в течение года — ${h} ₽. Каков оптимальный размер одной поставки по формуле Уилсона Q = √(2DS/H)?`, q, 'Большие поставки — дорогое хранение, маленькие — много поставок. Формула находит баланс.', [`Q = √(2 · ${big(D)} · ${s} : ${h}) = √${big(q * q)} = ${q}.`, `Значит, выгодно делать ${D / q} ${plural(D / q, 'поставку', 'поставки', 'поставок')} в год по ${q} единиц.`, 'При таком размере затраты на поставки равны затратам на хранение — их сумма минимальна.'], `e:${D}:${s}:${h}`, { ref: 2 })
}


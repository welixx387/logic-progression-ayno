const HINT = 'Вспомните правило, которое проходили на уроках русского языка.'

function table(rng: Rng, items: Pair[], ask: (x: string) => string, why: (x: string, a: string) => string, key: string): Draft {
  return { ...pairQuestion(rng, items, (p) => p[1], (p) => ask(p[0]), (p) => why(p[0], p[1]), key), hint: HINT }
}

function spelling(rng: Rng): Draft {
  const [gap, right, wrong, why] = rng.pick(SPELLING)
  return {
    kind: 'choice',
    prompt: `Как правильно написать: ${gap}?`,
    ...withOptions(right, wrong, rng, wrong.length + 1),
    hint: HINT,
    solution: why,
    key: `spell:${gap}`,
  }
}

function stress(rng: Rng): Draft {
  const [right, wrong] = rng.pick(STRESS)
  return {
    kind: 'choice',
    prompt: 'Где правильно поставлено ударение? Ударная гласная выделена заглавной буквой.',
    ...withOptions(right, [wrong], rng, 2),
    hint: 'Это слово из орфоэпического словника ЕГЭ — такие ударения стоит выучить.',
    solution: `Правильно: ${right}.`,
    key: `stress:${right}`,
  }
}

function paronym(rng: Rng): Draft {
  const [phrase, right, wrong, why] = rng.pick(PARONYMS)
  return {
    kind: 'choice',
    prompt: `Какое слово нужно вставить: «${phrase}»?`,
    ...withOptions(right, [wrong], rng, 2),
    hint: 'Это паронимы — похожие по звучанию слова с разным значением.',
    solution: `${capitalize(phrase.replace('…', right))}. ${why}`,
    key: `paronym:${right}`,
  }
}

function form(rng: Rng): Draft {
  const [right, wrong, why] = rng.pick(FORMS)
  return {
    kind: 'choice',
    prompt: 'Какой вариант соответствует норме литературного языка?',
    ...withOptions(right, wrong, rng, wrong.length + 1),
    hint: 'Вспомните, как образуются формы этого слова.',
    solution: `Правильно: «${right}». ${why}`,
    key: `form:${right}`,
  }
}

function generate(level: Level, rng: Rng, index: number): Draft | null {
  const even = index % 2 === 0
  switch (level) {
    case 1:
      return even
        ? table(rng, POS, (w) => `К какой части речи относится слово «${w}»?`, (w, p) => `«${w}» — ${p.toLowerCase()}.`, 'pos')
        : spelling(rng)
    case 2:
      return even
        ? table(rng, ONE_PART, (s) => `Каким является односоставное предложение «${s}»?`, (s, t) => `${t}. ${ONE_PART_WHY[t]}`, 'one')
        : table(rng, LINKS, (p) => `Какой вид подчинительной связи в словосочетании «${p}»?`, (p, t) => `${t}. ${LINK_WHY[t]}`, 'link')
    case 3:
      return even
        ? table(rng, COMPLEX, (s) => `Каким является сложное предложение «${s}»?`, (s, t) => `${t}. ${COMPLEX_WHY[t]}`, 'complex')
        : table(rng, CLAUSES, (s) => `Какое придаточное в предложении «${s}»?`, (s, t) => `${t}. ${CLAUSE_WHY[t]}`, 'clause')
    case 4:
      return even ? stress(rng) : paronym(rng)
    default:
      return even
        ? form(rng)
        : table(rng, STYLES, (s) => `К какому стилю речи относится текст «${s}»?`, (s, t) => `${t} стиль. ${STYLE_WHY[t]}`, 'style')
  }
}

export const russianGenerator: ModuleGenerator = {
  module: 'russian',
  targets: { 1: 10, 2: 10, 3: 10, 4: 10, 5: 10 },
  make: generate,
}

export function russian(): Task[] {
  return collect(russianGenerator)
}
